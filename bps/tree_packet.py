"""Generate one in-tree rstom packet file from a shape and wire body."""

from __future__ import annotations

from dataclasses import dataclass

from bps.emit_rstom import _PacketBody
from bps.errors import EmitError
from bps.minestom import Unit
from bps.shapes import FieldShape, Shape

_COPY_TYPES = frozenset(
    {
        "i8",
        "i16",
        "i32",
        "i64",
        "u8",
        "u16",
        "u32",
        "u64",
        "f32",
        "f64",
        "bool",
        "Uuid",
    }
)

_MAX_LINES = 400


def _validate_shape(shape: Shape) -> None:
    if shape.form == "unit" and shape.fields:
        raise EmitError(f"{shape.module}: unit shape must have no fields")
    if shape.serializer.style == "constant" and shape.form != "unit":
        raise EmitError(f"{shape.module}: constant serializer requires unit form")


def _is_copy_field(rust_type: str) -> bool:
    if rust_type.startswith("Option<") and rust_type.endswith(">"):
        inner = rust_type[len("Option<") : -1]
        return _is_copy_field(inner)
    if rust_type.startswith("Vec<"):
        return False
    return rust_type in _COPY_TYPES


def _adapt_tree_writes(writes: str, fields: tuple[FieldShape, ...]) -> str:
    out = writes
    for f in fields:
        if _is_copy_field(f.type):
            out = out.replace(f"value.{f.name}.clone()", f"value.{f.name}")
    return out


def _field_init_list(fields: tuple[FieldShape, ...]) -> str:
    return ",\n            ".join(f.name for f in fields)


def _read_box(cls: str, form: str, fields: tuple[FieldShape, ...]) -> str:
    if form == "unit":
        return f"        Box::new({cls})"
    if len(fields) == 1:
        return f"        Box::new({cls} {{ {fields[0].name} }})"
    init = _field_init_list(fields)
    return f"        Box::new({cls} {{\n            {init},\n        }})"


def _derive_attr(derives: tuple[str, ...]) -> str:
    if not derives:
        return ""
    return f"#[derive({', '.join(derives)})]\n"


def _doc_lines(prefix: str, lines: tuple[str, ...]) -> str:
    return "".join(f"{prefix}{line}\n" for line in lines)


def _banner(unit: Unit) -> str:
    pkt = unit.pkt.name
    routes = ", ".join(f"{r.state}.{r.direction} 0x{r.packet_id:02x}" for r in unit.routes)
    return (
        f"//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: "
        f"BPS packet `{pkt}`, routed {routes}.\n"
    )


def _marker_imports(unit: Unit) -> tuple[str, str]:
    name = unit.cls.name
    if unit.cls.group == "client":
        imports = (
            "use crate::network::packet::client::client_packet::"
            "{ClientPacket, ClientPacketGroup};\n"
        )
        impls = f"impl ClientPacket for {name} {{}}\nimpl ClientPacketGroup for {name} {{}}\n"
        return imports, impls
    imports = (
        "use crate::network::packet::server::server_packet::"
        "{ServerPacket, ServerPacketGroup};\n"
    )
    impls = f"impl ServerPacket for {name} {{}}\nimpl ServerPacketGroup for {name} {{}}\n"
    return imports, impls


def _use_block(
    unit: Unit,
    shape: Shape,
    body: _PacketBody,
) -> str:
    lines = ["use std::sync::Arc;\n", "\n"]
    marker_import, _ = _marker_imports(unit)
    needs_buffer = shape.serializer.style == "struct"
    if needs_buffer:
        lines.append("use crate::network::buffer::NetworkBuffer;\n")
    lines.append(marker_import)
    lines.append("use crate::network::packet::packet::Packet;\n")
    if shape.serializer.style == "constant":
        lines.append(
            "use crate::network::packet::serializer::{ConstantSerializer, PacketSerializer};\n"
        )
    else:
        lines.append(
            "use crate::network::packet::serializer::{PacketSerializer, PacketValue, downcast};\n"
        )
    if body.used_wires:
        if len(body.used_wires) == 1:
            lines.append(f"use crate::network::types::{body.used_wires[0]};\n")
        else:
            lines.append(f"use crate::network::types::{{{', '.join(body.used_wires)}}};\n")
    if body.needs_fixed_raw_bytes:
        lines.append("use crate::network::types::fixed_raw_bytes;\n")
    if "Uuid" in body.rtypes:
        lines.append("use crate::network::uuid::Uuid;\n")
    if "CoordVec" in body.rtypes:
        lines.append("use crate::coordinate::Vec as CoordVec;\n")
    return "".join(lines)


def _struct_decl(shape: Shape) -> str:
    docs = _doc_lines("/// ", shape.struct_docs)
    derive = _derive_attr(shape.derives)
    if shape.form == "unit":
        return f"{docs}{derive}pub struct {shape.cls};"
    field_lines: list[str] = []
    for f in shape.fields:
        field_lines.append(_doc_lines("    /// ", f.docs).rstrip("\n"))
        field_lines.append(f"    pub {f.name}: {f.type},")
    if field_lines and field_lines[-1].endswith(","):
        field_lines[-1] = field_lines[-1][:-1]
    fields = "\n".join(field_lines)
    return f"{docs}{derive}pub struct {shape.cls} {{\n{fields}\n}}"


def _new_fn(shape: Shape) -> str:
    if not shape.new.present:
        return ""
    lines: list[str] = []
    lines.append(_doc_lines("    /// ", shape.new.docs).rstrip("\n"))
    if shape.new.must_use:
        lines.append("    #[must_use]")
    for attr in shape.new.attrs:
        lines.append(f"    {attr}")
    params = ", ".join(f"{f.name}: {f.type}" for f in shape.fields)
    const_kw = "const " if shape.new.const else ""
    init = _field_init_list(shape.fields)
    if shape.form == "unit":
        body = "        Self"
    else:
        body = f"        Self {{ {init} }}"
    lines.append(f"    pub {const_kw}fn new({params}) -> Self {{")
    lines.append(body)
    lines.append("    }")
    return "\n".join(lines)


def _serializer_fn(shape: Shape) -> str:
    lines: list[str] = []
    lines.append(_doc_lines("    /// ", shape.serializer_fn_docs).rstrip("\n"))
    if shape.serializer_fn_must_use:
        lines.append("    #[must_use]")
    lines.append("    pub fn serializer() -> Arc<dyn PacketSerializer> {")
    if shape.serializer.style == "constant":
        lines.append(f"        Arc::new(ConstantSerializer::new({shape.serializer.name}))")
    else:
        lines.append(f"        Arc::new({shape.serializer.name})")
    lines.append("    }")
    return "\n".join(lines)


def _inherent_impl(shape: Shape) -> str:
    parts = [_new_fn(shape), _serializer_fn(shape)]
    body = "\n\n".join(p for p in parts if p)
    if not body:
        return ""
    return f"impl {shape.cls} {{\n{body}\n}}\n\n"


def _serializer_impl(unit: Unit, shape: Shape, body: _PacketBody) -> str:
    if shape.serializer.style == "constant":
        return ""
    ser = shape.serializer.name
    vis = "pub " if shape.serializer.public else ""
    docs = _doc_lines("/// ", shape.serializer.docs)
    writes = _adapt_tree_writes(body.writes, shape.fields)
    read_box = _read_box(shape.cls, shape.form, shape.fields)
    return (
        f"{docs}{vis}struct {ser};\n\n"
        f"impl PacketSerializer for {ser} {{\n"
        f"    fn write(&self, buffer: &mut NetworkBuffer, value: &PacketValue) {{\n"
        f"        let value = downcast::<{shape.cls}>(value);\n"
        f"{writes}\n"
        f"    }}\n\n"
        f"    fn read(&self, buffer: &mut NetworkBuffer) -> PacketValue {{\n"
        f"{body.reads}\n"
        f"{read_box}\n"
        f"    }}\n"
        f"}}\n"
    )


def _extras_tail(shape: Shape) -> str:
    if not shape.extras:
        return ""
    stem = shape.module.rsplit("/", 1)[-1]
    return f'\n#[path = "{stem}.ext.rs"]\nmod ext;\npub use ext::*;\n'


def tree_packet(unit: Unit, shape: Shape, body: _PacketBody) -> str:
    """Render the in-tree packet source for ``unit`` using ``shape`` and ``body``."""
    _validate_shape(shape)
    if shape.cls != unit.cls.name:
        raise EmitError(f"{shape.module}: shape class {shape.cls!r} != unit {unit.cls.name!r}")

    parts: list[str] = [_banner(unit), "//!\n"]
    if shape.module_docs:
        parts.append(_doc_lines("//! ", shape.module_docs))
    parts.append("\n")
    parts.append(_use_block(unit, shape, body))
    parts.append("\n")
    parts.append(_struct_decl(shape))
    parts.append("\n\n")
    parts.append(_inherent_impl(shape))
    parts.append(f"impl Packet for {shape.cls} {{\n")
    parts.append(f'    const CLASS_NAME: &\'static str = "{unit.cls.java}";\n')
    parts.append("}\n\n")
    _, marker_impls = _marker_imports(unit)
    parts.append(marker_impls)
    parts.append("\n")
    parts.append(_serializer_impl(unit, shape, body))
    parts.append(_extras_tail(shape))
    text = "".join(parts)
    if text.count("\n") + (0 if text.endswith("\n") else 1) > _MAX_LINES:
        raise EmitError(f"{shape.module}: generated file exceeds {_MAX_LINES} lines")
    if not text.endswith("\n"):
        text += "\n"
    return text


# Brief alias for the task interface name.
_tree_packet = tree_packet
