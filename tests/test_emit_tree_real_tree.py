"""Emit all 64 eligible wave-1 packets into a copied rstom tree."""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import time
import unittest
from pathlib import Path

from bps.emit_tree import emit_tree
from bps.minestom import build_units
from bps.shapes import extract_shapes_for_units, hand_packet_path, module_path, shape_to_json

from tests.rstom_tables import RSTOM, real_table
from tests.test_varint import load_minecraft

RSTOM_PACKET = RSTOM / "crates" / "rstom" / "src" / "network" / "packet"
COMMITTED_SHAPES = Path(__file__).resolve().parents[1] / "targets" / "rstom" / "shapes"


@unittest.skipUnless(RSTOM_PACKET.is_dir(), "rstom worktree packet sources not present")
class EmitTreeRealTreeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.resolved = load_minecraft()
        cls.table = real_table()
        cls.units = build_units(cls.resolved, cls.table)

    def test_emit_all_sixty_four_eligible_packets(self) -> None:
        t0 = time.perf_counter()
        committed = {
            json.loads(p.read_text(encoding="utf-8"))["class"]
            for p in COMMITTED_SHAPES.rglob("*.json")
        }
        pairs = [
            (unit, shape)
            for unit, shape in extract_shapes_for_units(
                self.resolved, RSTOM, self.units, eligible_only=True
            )
            if shape.cls in committed
        ]
        self.assertEqual(len(pairs), 64)

        with tempfile.TemporaryDirectory() as td:
            ws = Path(td) / "rstom"
            ws.mkdir()
            shutil.copytree(
                RSTOM_PACKET,
                ws / "crates" / "rstom" / "src" / "network" / "packet",
            )
            gen_schema = RSTOM / "tools" / "packets_gen" / "schema" / "packets.json"
            dest_schema = ws / "tools" / "packets_gen" / "schema" / "packets.json"
            dest_schema.parent.mkdir(parents=True)
            shutil.copyfile(gen_schema, dest_schema)

            shapes_dir = Path(td) / "shapes"
            shaped_modules = set()
            for unit, shape in pairs:
                shaped_modules.add(module_path(unit))
                out = shapes_dir / f"{module_path(unit)}.json"
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(shape_to_json(shape), encoding="utf-8")
                if shape.extras:
                    ext = hand_packet_path(ws, unit).parent / shape.extras
                    ext.parent.mkdir(parents=True, exist_ok=True)
                    ext.write_text("//! scratch\n", encoding="utf-8")

            emit_tree(self.resolved, ws, self.table, shapes_dir)
            pkt_root = ws / "crates" / "rstom" / "src" / "network" / "packet"
            generated = []
            for module in shaped_modules:
                path = pkt_root / f"{module}.rs"
                text = path.read_text(encoding="utf-8")
                self.assertTrue(text.startswith("//! Generated by `bps emit rust`"), msg=module)
                generated.append(path)

            self.assertEqual(len(generated), 64)
            rustfmt = shutil.which("rustfmt")
            self.assertIsNotNone(rustfmt)
            for path in generated:
                text = path.read_text(encoding="utf-8")
                lines = text.count("\n") + (0 if text.endswith("\n") else 1)
                self.assertLessEqual(lines, 400, msg=path)
                proc = subprocess.run(
                    [rustfmt, "--edition", "2024", "--check", str(path)],
                    capture_output=True,
                    text=True,
                )
                self.assertEqual(proc.returncode, 0, msg=f"{path}: {proc.stderr}")

            first_bytes = {p: p.read_bytes() for p in generated}
            emit_tree(self.resolved, ws, self.table, shapes_dir)
            self.assertEqual(emit_tree(self.resolved, ws, self.table, shapes_dir, check=True), [])
            for path, data in first_bytes.items():
                self.assertEqual(path.read_bytes(), data, msg=path)

        elapsed = time.perf_counter() - t0
        print(f"real-tree emit test elapsed {elapsed:.1f}s")


if __name__ == "__main__":
    unittest.main()
