class G1aCliExtrasTest(unittest.TestCase):
    """G1(a): CLI shapes extract preserves extras for generated packets with ext siblings."""

    def test_cli_extract_preserves_extras(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            ws = Path(td) / "ws"
            pkt_dir = ws / "crates/rstom/src/network/packet/server/play"
            pkt_dir.mkdir(parents=True)
            pkt = pkt_dir / "probe_packet.rs"
            pkt.write_text(
                "//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: probe\n"
                "//! Port of `net.minestom.server.network.packet.server.play.ProbePacket`.\n"
                "use std::sync::Arc;\n"
                "use crate::network::packet::packet::Packet;\n"
                "use crate::network::packet::serializer::{PacketSerializer, PacketValue};\n"
                "use crate::network::packet::server::server_packet::{ServerPacket, ServerPacketGroup};\n"
                "#[derive(Copy, Clone, Debug, PartialEq, Eq)]\n"
                "pub struct ProbePacket { pub id: i32 }\n"
                "impl ProbePacket {\n"
                "    pub fn new(id: i32) -> Self { Self { id } }\n"
                "    pub fn serializer() -> Arc<dyn PacketSerializer> { Arc::new(ProbePacketSerializer) }\n"
                "}\n"
                "impl Packet for ProbePacket {}\n"
                "impl ServerPacket for ProbePacket {}\n"
                "impl ServerPacketGroup for ProbePacket {}\n"
                "struct ProbePacketSerializer;\n"
                "impl PacketSerializer for ProbePacketSerializer {\n"
                "    fn write(&self, _b: &mut (), _v: &PacketValue) {}\n"
                "    fn read(&self, _b: &mut ()) -> PacketValue { Box::new(ProbePacket { id: 0 }) }\n"
                "}\n",
                encoding="utf-8",
            )
            ext = pkt_dir / "probe_packet.ext.rs"
            ext.write_text("//! Hand-written helpers for ProbePacket.\n", encoding="utf-8")

            out = Path(td) / "shapes"
            out.mkdir()
            schema = Path(td) / "p.bps"
            schema.write_text(probe_source(ROOT, "packet probe { id: i32be }"), encoding="utf-8")
            table_path = ws / "tools/packets_gen/schema/packets.json"
            table_path.parent.mkdir(parents=True)
            table_path.write_text(json.dumps(PROBE_SCHEMA), encoding="utf-8")

            proc = subprocess.run(
                [
                    "python",
                    "-m",
                    "bps.cli",
                    "shapes",
                    "extract",
                    str(schema),
                    "--rstom",
                    str(ws),
                    "--eligible",
                    "--out",
                    str(out),
                ],
                capture_output=True,
                text=True,
                cwd=str(ROOT),
            )
            self.assertEqual(proc.returncode, 0, msg=proc.stderr)
            shape_path = out / "server/play/probe_packet.json"
            self.assertTrue(shape_path.is_file(), msg=f"shape not written: {shape_path}")
            obj = json.loads(shape_path.read_text())
            self.assertEqual(obj["extras"], "probe_packet.ext.rs")


@unittest.skipUnless(_worktree_present(), "rstom worktree not present")
class G1bLedgerFixedPointTest(unittest.TestCase):
    """G1(b): CLI extraction over the swapped worktree reproduces the committed ledger byte-for-byte."""

    def test_all_64_ledger_entries_reproduce(self) -> None:
        ledger = load_ledger(SHAPES)
        self.assertEqual(len(ledger), 64)
        with tempfile.TemporaryDirectory() as td:
            out = Path(td) / "extracted"
            proc = subprocess.run(
                [
                    "python",
                    "-m",
                    "bps.cli",
                    "shapes",
                    "extract",
                    str(SCHEMA),
                    "--rstom",
                    str(RSTOM),
                    "--out",
                    str(out),
                ],
                capture_output=True,
                text=True,
                cwd=str(ROOT),
            )
            self.assertEqual(proc.returncode, 0, msg=proc.stderr)
            mismatches: list[str] = []
            for module in sorted(ledger):
                committed = SHAPES / f"{module}.json"
                extracted = out / f"{module}.json"
                if not extracted.is_file():
                    mismatches.append(f"{module}: not extracted")
                    continue
                if committed.read_bytes() != extracted.read_bytes():
                    mismatches.append(f"{module}: byte mismatch")
            self.assertEqual(mismatches, [], msg=f"{len(mismatches)} mismatches: {mismatches[:5]}")


class G1cOrphanExtGuardTest(unittest.TestCase):
    """G1(c): emit rstom-tree refuses when ext file exists but shape has no extras."""

    def test_orphan_ext_raises(self) -> None:
        resolved, _ = _analyze_keep_alive()
        shape = replace(_keep_alive_shape(), extras=None)
        shapes = Path(tempfile.mkdtemp())
        _write_shape(shapes, shape)
        ws = Path(tempfile.mkdtemp()) / "rstom"
        ws.mkdir()
        (ws / "tools/packets_gen/schema").mkdir(parents=True)
        (ws / "tools/packets_gen/schema/packets.json").write_text(
            json.dumps(KEEP_ALIVE_TABLE_DATA), encoding="utf-8"
        )
        pkt_dir = ws / "crates/rstom/src/network/packet/client/common"
        pkt_dir.mkdir(parents=True)
        pkt = pkt_dir / "client_keep_alive_packet.rs"
        pkt.write_text(
            "//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: keep_alive\n"
            "#[path = \"client_keep_alive_packet.ext.rs\"]\nmod ext;\n",
            encoding="utf-8",
        )
        ext = pkt_dir / "client_keep_alive_packet.ext.rs"
        ext.write_text("//! orphan\n", encoding="utf-8")
        with self.assertRaises(EmitError) as ctx:
            emit_tree(resolved, ws, KEEP_ALIVE_TABLE, shapes)
        self.assertIn("would be orphaned", str(ctx.exception))
        self.assertIn("client_keep_alive_packet.ext.rs", str(ctx.exception))


class G2CheckReadOnlyTest(unittest.TestCase):
    """G2: emit_tree(check=True) creates nothing and leaks no temp files."""

    def test_check_creates_no_files(self) -> None:
        resolved, _ = _analyze_keep_alive()
        shapes = Path(tempfile.mkdtemp())
        _write_shape(shapes, _keep_alive_shape())
        ws = Path(tempfile.mkdtemp()) / "rstom"
        ws.mkdir()
        (ws / "tools/packets_gen/schema").mkdir(parents=True)
        (ws / "tools/packets_gen/schema/packets.json").write_text(
            json.dumps(KEEP_ALIVE_TABLE_DATA), encoding="utf-8"
        )
        before = {p: p.stat().st_mtime_ns for p in ws.rglob("*") if p.is_file()}
        emit_tree(resolved, ws, KEEP_ALIVE_TABLE, shapes, check=True)
        after = {p: p.stat().st_mtime_ns for p in ws.rglob("*") if p.is_file()}
        self.assertEqual(before, after, msg="check=True modified workspace files")

    def test_rustfmt_oserror_no_temp_leak(self) -> None:
        resolved, _ = _analyze_keep_alive()
        shapes = Path(tempfile.mkdtemp())
        _write_shape(shapes, _keep_alive_shape())
        ws = Path(tempfile.mkdtemp()) / "rstom"
        ws.mkdir()
        (ws / "tools/packets_gen/schema").mkdir(parents=True)
        (ws / "tools/packets_gen/schema/packets.json").write_text(
            json.dumps(KEEP_ALIVE_TABLE_DATA), encoding="utf-8"
        )
        tmp_before = set(Path(tempfile.gettempdir()).glob("tmp*.rs"))
        with patch("bps.emit_tree.subprocess.run", side_effect=OSError("mock")):
            with self.assertRaises(OSError):
                emit_tree(resolved, ws, KEEP_ALIVE_TABLE, shapes)
        tmp_after = set(Path(tempfile.gettempdir()).glob("tmp*.rs"))
        self.assertEqual(tmp_before, tmp_after, msg="temp file leaked after OSError")


class G3FramesGuardTest(unittest.TestCase):
    """G3: tree_packet raises EmitError when body references crate::frames::."""

    def test_frames_walker_raises(self) -> None:
        resolved, unit = _analyze_keep_alive()
        shape = _keep_alive_shape()
        body = _PacketBody(
            fields=[],
            field_types={},
            writes="",
            reads="        let raw = crate::frames::nbt(&buf) as i32;",
            ctor="",
            init="",
            used_wires=[],
            needs_fixed_raw_bytes=False,
            rtypes=set(),
        )
        with self.assertRaises(EmitError) as ctx:
            tree_packet(unit, shape, body)
        self.assertIn("frames walker", str(ctx.exception))
        self.assertIn("nbt", str(ctx.exception))


class G4RstomDefaultTest(unittest.TestCase):
    """G4: RSTOM defaults to BPS_RSTOM_DIR, then rstom-bps, then rstom."""

    def test_env_var_wins(self) -> None:
        with patch.dict(os.environ, {"BPS_RSTOM_DIR": "/tmp/custom"}):
            import importlib

            import tests.rstom_tables as rt

            importlib.reload(rt)
            self.assertEqual(str(rt.RSTOM), "/tmp/custom")

    def test_rstom_bps_preferred_over_rstom(self) -> None:
        without_env = {k: v for k, v in os.environ.items() if k != "BPS_RSTOM_DIR"}
        with patch.dict(os.environ, without_env, clear=True):
            import importlib

            import tests.rstom_tables as rt

            importlib.reload(rt)
            protoc = Path(rt.__file__).resolve().parents[1]
            if (protoc.parent / "rstom-bps").is_dir():
                self.assertEqual(rt.RSTOM, protoc.parent / "rstom-bps")
            else:
                self.assertEqual(rt.RSTOM, protoc.parent / "rstom")


