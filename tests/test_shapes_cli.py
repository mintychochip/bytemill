"""CLI ``shapes extract`` behaviour against an rstom workspace."""

from __future__ import annotations

import json
import subprocess
import tempfile
import unittest
from pathlib import Path

from bps.shapes import load_ledger

from tests.rstom_tables import PROBE_SCHEMA, RSTOM, probe_source
from tests.test_emit_tree import ROOT

SHAPES = ROOT / "targets" / "rstom" / "shapes"
SCHEMA = ROOT / "schemas" / "minecraft_26_3_wiki.bps"


def _worktree_present() -> bool:
    return (RSTOM / "crates" / "rstom" / "src" / "network" / "packet").is_dir()


class ShapesCliExtractExtrasTest(unittest.TestCase):
    """``shapes extract`` records sibling ``.ext.rs`` files in shape JSON."""

    def test_eligible_extract_sets_extras_from_ext_sibling(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            ws = Path(td) / "ws"
            pkt_dir = ws / "crates/rstom/src/network/packet/server/play"
            pkt_dir.mkdir(parents=True)
            pkt = pkt_dir / "probe_packet.rs"
            pkt.write_text(
                "//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: probe\n"
                "//! Port of `net.minestom.server.network.packet.server.play.ProbePacket`.\n"
                "use std::sync::Arc;\n"
                "use crate::network::packet::packet::Packet;\n"
                "use crate::network::packet::serializer::{PacketSerializer, PacketValue};\n"
                "use crate::network::packet::server::server_packet::{ServerPacket, ServerPacketGroup};\n"
                "#[derive(Copy, Clone, Debug, PartialEq, Eq)]\n"
                "pub struct ProbePacket { pub id: i32 }\n"
                "impl ProbePacket {\n"
                "    pub fn new(id: i32) -> Self { Self { id } }\n"
                "    pub fn serializer() -> Arc<dyn PacketSerializer> { Arc::new(ProbePacketSerializer) }\n"
                "}\n"
                "impl Packet for ProbePacket {}\n"
                "impl ServerPacket for ProbePacket {}\n"
                "impl ServerPacketGroup for ProbePacket {}\n"
                "struct ProbePacketSerializer;\n"
                "impl PacketSerializer for ProbePacketSerializer {\n"
                "    fn write(&self, _b: &mut (), _v: &PacketValue) {}\n"
                "    fn read(&self, _b: &mut ()) -> PacketValue { Box::new(ProbePacket { id: 0 }) }\n"
                "}\n",
                encoding="utf-8",
            )
            ext = pkt_dir / "probe_packet.ext.rs"
            ext.write_text("//! Hand-written helpers for ProbePacket.\n", encoding="utf-8")

            out = Path(td) / "shapes"
            out.mkdir()
            schema = Path(td) / "p.bps"
            schema.write_text(probe_source(ROOT, "packet probe { id: i32be }"), encoding="utf-8")
            table_path = ws / "tools/packets_gen/schema/packets.json"
            table_path.parent.mkdir(parents=True)
            table_path.write_text(json.dumps(PROBE_SCHEMA), encoding="utf-8")

            proc = subprocess.run(
                [
                    "python",
                    "-m",
                    "bps.cli",
                    "shapes",
                    "extract",
                    str(schema),
                    "--rstom",
                    str(ws),
                    "--eligible",
                    "--out",
                    str(out),
                ],
                capture_output=True,
                text=True,
                cwd=str(ROOT),
            )
            self.assertEqual(proc.returncode, 0, msg=proc.stderr)
            shape_path = out / "server/play/probe_packet.json"
            self.assertTrue(shape_path.is_file(), msg=f"shape not written: {shape_path}")
            obj = json.loads(shape_path.read_text())
            self.assertEqual(obj["extras"], "probe_packet.ext.rs")


@unittest.skipUnless(_worktree_present(), "rstom worktree not present")
class ShapesCliLedgerFixedPointTest(unittest.TestCase):
    """CLI extraction over the worktree matches the committed shape ledger."""

    def test_worktree_extract_matches_committed_ledger_bytes(self) -> None:
        ledger = load_ledger(SHAPES)
        self.assertEqual(len(ledger), 64)
        with tempfile.TemporaryDirectory() as td:
            out = Path(td) / "extracted"
            proc = subprocess.run(
                [
                    "python",
                    "-m",
                    "bps.cli",
                    "shapes",
                    "extract",
                    str(SCHEMA),
                    "--rstom",
                    str(RSTOM),
                    "--out",
                    str(out),
                ],
                capture_output=True,
                text=True,
                cwd=str(ROOT),
            )
            self.assertEqual(proc.returncode, 0, msg=proc.stderr)
            mismatches: list[str] = []
            for module in sorted(ledger):
                committed = SHAPES / f"{module}.json"
                extracted = out / f"{module}.json"
                if not extracted.is_file():
                    mismatches.append(f"{module}: not extracted")
                    continue
                if committed.read_bytes() != extracted.read_bytes():
                    mismatches.append(f"{module}: byte mismatch")
            self.assertEqual(mismatches, [], msg=f"{len(mismatches)} mismatches: {mismatches[:5]}")


if __name__ == "__main__":
    unittest.main()
