//! Rust-source text primitives for shape extraction.
//!
//! Port of `bps/shapes/scan.py`. Offsets are byte offsets into `&str`
//! (Python uses code-point offsets); all delimiters scanned are ASCII, so
//! positions are identical for ASCII sources. Character-level checks
//! (`isalnum`, char literals) decode code points, matching Python.

use crate::errors::{BmlResult, shape};

/// Substring `s[a..b]` with Python slice clamping; never panics.
pub(crate) fn sub(s: &str, a: usize, b: usize) -> &str {
    let b = b.min(s.len());
    if a >= b {
        return "";
    }
    s.get(a..b).unwrap_or("")
}

/// `src.startswith(p, pos)`.
pub(crate) fn sw(s: &str, pos: usize, p: &str) -> bool {
    s.as_bytes()
        .get(pos..)
        .is_some_and(|x| x.starts_with(p.as_bytes()))
}

/// `src.find(needle, pos)` as an option (Python `-1` maps to `None`).
pub(crate) fn find_from(s: &str, pos: usize, needle: &str) -> Option<usize> {
    s.get(pos..)?.find(needle).map(|i| i + pos)
}

/// Byte at `pos`, if in range.
pub(crate) fn at(s: &str, pos: usize) -> Option<u8> {
    s.as_bytes().get(pos).copied()
}

/// Code point starting at byte `pos`, if `pos` is a char boundary in range.
fn char_at(s: &str, pos: usize) -> Option<char> {
    s.get(pos..)?.chars().next()
}

/// `_doc_line_text`.
pub fn doc_line_text(line: &str) -> String {
    for prefix in ["//!", "///"] {
        if let Some(rest) = line.strip_prefix(prefix) {
            return rest.strip_prefix(' ').unwrap_or(rest).to_string();
        }
    }
    line.to_string()
}

/// `_leading_module_docs`.
pub(crate) fn leading_module_docs(src: &str) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    for line in src.split_inclusive('\n') {
        let stripped = line.trim();
        if stripped.starts_with("//!") {
            let text = doc_line_text(stripped);
            if text.starts_with("Generated by") || text.is_empty() {
                continue;
            }
            lines.push(text);
        } else if stripped.is_empty() && lines.is_empty() {
            continue;
        } else {
            break;
        }
    }
    lines
}

/// `_skip_block_comment`: offset past the (nested) block comment at `pos`.
pub(crate) fn skip_block_comment(src: &str, pos: usize) -> usize {
    let mut depth: i64 = 0;
    let mut i = pos;
    while i < src.len() {
        if sw(src, i, "/*") {
            depth += 1;
            i += 2;
        } else if sw(src, i, "*/") {
            depth -= 1;
            i += 2;
            if depth == 0 {
                return i;
            }
        } else {
            i += 1;
        }
    }
    src.len()
}

/// `_skip_trivia`: skip whitespace and non-doc comments.
pub(crate) fn skip_trivia(src: &str, mut pos: usize) -> usize {
    while pos < src.len() {
        if sw(src, pos, "//") && !sw(src, pos, "///") {
            pos = match find_from(src, pos, "\n") {
                None => src.len(),
                Some(nl) => nl + 1,
            };
            continue;
        }
        if sw(src, pos, "/*") {
            pos = skip_block_comment(src, pos);
            continue;
        }
        if matches!(at(src, pos), Some(b' ' | b'\t' | b'\r' | b'\n')) {
            pos += 1;
            continue;
        }
        return pos;
    }
    pos
}

/// `_line_start`.
pub(crate) fn line_start(src: &str, pos: usize) -> usize {
    match sub(src, 0, pos).rfind('\n') {
        None => 0,
        Some(nl) => nl + 1,
    }
}

/// `_attr_block_end`: index after the `]` closing `#[` at `hash_pos`.
pub(crate) fn attr_block_end(src: &str, hash_pos: usize) -> BmlResult<usize> {
    if !sw(src, hash_pos, "#[") {
        return Err(shape("expected #["));
    }
    let mut depth: i64 = 0;
    let mut i = hash_pos + 1;
    while i < src.len() {
        let c = src.as_bytes()[i];
        if c == b'"' || c == b'\'' {
            i = skip_rust_string(src, i);
            continue;
        }
        if c == b'[' {
            depth += 1;
        } else if c == b']' {
            depth -= 1;
            if depth == 0 {
                return Ok(i + 1);
            }
        }
        i += 1;
    }
    Ok(src.len())
}

/// `_line_in_attr_prefix`.
fn line_in_attr_prefix(src: &str, line_begin: usize, item_line: usize) -> BmlResult<bool> {
    let mut i = 0;
    while i < item_line {
        if sw(src, i, "#[") {
            let end = attr_block_end(src, i)?;
            if line_begin < end && line_begin >= line_start(src, i) {
                return Ok(true);
            }
            i = end;
            continue;
        }
        i += 1;
    }
    Ok(false)
}

/// `_docs_and_attrs_before`: (doc lines, attribute start) for the item at `item_pos`.
pub fn docs_and_attrs_before(src: &str, item_pos: usize) -> BmlResult<(Vec<String>, usize)> {
    let item = advance_item_start(src, item_pos)?;
    let item_line = line_start(src, item);
    let mut attr_start = item;
    let mut doc_lines: Vec<String> = Vec::new();
    let mut line_begin = item_line;
    if line_begin > 0 {
        line_begin = line_start(src, line_begin - 1);
    } else {
        return Ok((Vec::new(), item));
    }
    loop {
        let line_end = find_from(src, line_begin, "\n").unwrap_or(src.len());
        let stripped = sub(src, line_begin, line_end).trim();
        if stripped.starts_with("///") {
            doc_lines.insert(0, doc_line_text(stripped));
        } else if stripped.starts_with("#[") {
            attr_start = attr_start.min(line_begin);
        } else if !stripped.is_empty() && !line_in_attr_prefix(src, line_begin, item_line)? {
            // Blank lines and the continuation lines of a multi-line attribute stay in the
            // block; anything else ends it.
            break;
        }
        if line_begin == 0 {
            break;
        }
        line_begin = line_start(src, line_begin - 1);
    }
    Ok((doc_lines, attr_start))
}

fn is_ident_start(c: u8) -> bool {
    c.is_ascii_alphabetic() || c == b'_'
}

fn is_ident_cont(c: u8) -> bool {
    c.is_ascii_alphanumeric() || c == b'_'
}

/// `_read_ident`: identifier at `pos` (after trivia) and the offset past it.
pub(crate) fn read_ident(src: &str, pos: usize) -> BmlResult<(String, usize)> {
    let pos = skip_trivia(src, pos);
    let b = src.as_bytes();
    if pos >= b.len() || !is_ident_start(b[pos]) {
        return Err(shape("expected identifier"));
    }
    let mut end = pos + 1;
    while end < b.len() && is_ident_cont(b[end]) {
        end += 1;
    }
    Ok((src[pos..end].to_string(), end))
}

/// `_matching_brace`: index of the `}` matching the `{` at `open_pos`.
pub(crate) fn matching_brace(src: &str, open_pos: usize) -> usize {
    skip_balanced(src, open_pos, b'{', b'}').saturating_sub(1)
}

/// `_raw_string_hashes`: hash count of the raw string whose quote is at `pos`.
fn raw_string_hashes(src: &str, pos: usize) -> Option<usize> {
    let b = src.as_bytes();
    let mut j = pos as isize - 1;
    while j >= 0 && b[j as usize] == b'#' {
        j -= 1;
    }
    if j < 0 || b[j as usize] != b'r' {
        return None;
    }
    let j = j as usize;
    let mut before = sub(src, 0, j).chars().next_back();
    if before == Some('b') {
        before = sub(src, 0, j - 1).chars().next_back();
    }
    if let Some(c) = before
        && (c.is_alphanumeric() || c == '_')
    {
        return None;
    }
    Some(pos - 1 - j)
}

/// `_skip_rust_string`.
pub(crate) fn skip_rust_string(src: &str, pos: usize) -> usize {
    let b = src.as_bytes();
    if pos >= b.len() {
        return pos;
    }
    if b[pos] == b'"' {
        let Some(hashes) = raw_string_hashes(src, pos) else {
            return skip_string(src, pos);
        };
        let close = format!("\"{}", "#".repeat(hashes));
        return match find_from(src, pos + 1, &close) {
            None => src.len(),
            Some(end) => end + close.len(),
        };
    }
    if b[pos] == b'\'' {
        if let Some(c1) = char_at(src, pos + 1) {
            let p2 = pos + 1 + c1.len_utf8();
            if c1 != '\\' && at(src, p2) == Some(b'\'') {
                return p2 + 1;
            }
        }
        if at(src, pos + 1) == Some(b'\\') {
            return skip_string(src, pos);
        }
        let mut nxt = pos + 1;
        while let Some(c) = char_at(src, nxt) {
            if !(c.is_alphanumeric() || c == '_') {
                break;
            }
            nxt += c.len_utf8();
        }
        return nxt;
    }
    pos + 1
}

/// `_skip_balanced`: offset past the balanced `open_ch ... close_ch` group at `pos`.
pub(crate) fn skip_balanced(src: &str, pos: usize, open_ch: u8, close_ch: u8) -> usize {
    let b = src.as_bytes();
    if pos >= b.len() || b[pos] != open_ch {
        return pos;
    }
    let mut depth: i64 = 0;
    let mut i = pos;
    while i < b.len() {
        let ch = b[i];
        if ch == b'"' || ch == b'\'' {
            i = skip_rust_string(src, i);
            continue;
        }
        if ch == open_ch {
            depth += 1;
        } else if ch == close_ch {
            depth -= 1;
            if depth == 0 {
                return i + 1;
            }
        }
        i += 1;
    }
    b.len()
}

/// `_skip_string`.
fn skip_string(src: &str, pos: usize) -> usize {
    let b = src.as_bytes();
    let quote = b[pos];
    let mut i = pos + 1;
    while i < b.len() {
        if b[i] == b'\\' {
            i += 2;
            continue;
        }
        if b[i] == quote {
            return i + 1;
        }
        i += 1;
    }
    b.len()
}

/// `_parse_struct_attrs`: the derive list of the struct at `struct_pos`.
pub(crate) fn parse_struct_attrs(
    src: &str,
    attr_start: usize,
    struct_pos: usize,
) -> BmlResult<Vec<String>> {
    let mut derives: Vec<String> = Vec::new();
    let mut pos = attr_start;
    while pos < struct_pos {
        pos = skip_trivia(src, pos);
        if pos >= struct_pos {
            break;
        }
        if !sw(src, pos, "#[") {
            break;
        }
        let end = matching_attr(src, pos);
        let attr_text = sub(src, pos, end);
        let alen = attr_text.len();
        let inner = if alen >= 3 {
            sub(attr_text, 2, alen - 1).trim()
        } else {
            ""
        };
        if let Some(rest) = inner.strip_prefix("derive(") {
            let close = match inner.rfind(')') {
                Some(i) => i,
                None => inner.len().saturating_sub(1),
            };
            derives = split_derives(sub(rest, 0, close.saturating_sub("derive(".len())));
        } else {
            let head = inner.split('(').next().unwrap_or("");
            return Err(shape(format!("attribute {head}")));
        }
        pos = end;
    }
    if derives.is_empty() {
        return Err(shape("missing derive on struct"));
    }
    Ok(derives)
}

/// `_matching_attr`: offset past the `]` closing the `#[` at `pos`.
pub(crate) fn matching_attr(src: &str, pos: usize) -> usize {
    if !sw(src, pos, "#[") {
        return pos;
    }
    let b = src.as_bytes();
    let mut depth: i64 = 0;
    let mut i = pos + 1;
    while i < b.len() {
        if b[i] == b'[' {
            depth += 1;
        } else if b[i] == b']' {
            depth -= 1;
            if depth == 0 {
                return i + 1;
            }
        }
        i += 1;
    }
    b.len()
}

/// `_split_derives`: split on top-level commas.
fn split_derives(inner: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut depth: i64 = 0;
    let mut cur = String::new();
    for ch in inner.chars() {
        if matches!(ch, '(' | '<' | '[') {
            depth += 1;
        } else if matches!(ch, ')' | '>' | ']') {
            depth -= 1;
        } else if ch == ',' && depth == 0 {
            let part = cur.trim().to_string();
            if !part.is_empty() {
                out.push(part);
            }
            cur.clear();
            continue;
        }
        cur.push(ch);
    }
    let part = cur.trim().to_string();
    if !part.is_empty() {
        out.push(part);
    }
    out
}

/// `_advance_item_start`: skip trivia, attributes and doc lines before an item.
pub fn advance_item_start(src: &str, mut pos: usize) -> BmlResult<usize> {
    loop {
        pos = skip_trivia(src, pos);
        if pos >= src.len() {
            return Ok(pos);
        }
        if sw(src, pos, "#[") {
            pos = matching_attr(src, pos);
            continue;
        }
        let line_end = find_from(src, pos, "\n").unwrap_or(src.len());
        let line = sub(src, pos, line_end).trim();
        if line.starts_with("///") || line.starts_with("#[") {
            pos = line_end + 1;
            continue;
        }
        return Ok(pos);
    }
}

/// `_read_type`: type text up to a top-level `,` or `}`, and the end offset.
pub(crate) fn read_type(src: &str, pos: usize) -> (String, usize) {
    let mut pos = skip_trivia(src, pos);
    let start = pos;
    let b = src.as_bytes();
    let mut depth_angle: i64 = 0;
    let mut depth_paren: i64 = 0;
    while pos < b.len() {
        let ch = b[pos];
        if ch == b'"' || ch == b'\'' {
            pos = skip_rust_string(src, pos);
            continue;
        }
        if ch == b'<' {
            depth_angle += 1;
        } else if ch == b'>' && depth_angle > 0 {
            depth_angle -= 1;
        } else if ch == b'(' {
            depth_paren += 1;
        } else if ch == b')' {
            depth_paren -= 1;
        } else if (ch == b',' || ch == b'}') && depth_angle == 0 && depth_paren == 0 {
            break;
        }
        pos += 1;
    }
    (sub(src, start, pos).trim().to_string(), pos)
}

/// `_parse_impl_header`: (trait, target, body_start, body_end, end).
pub(crate) fn parse_impl_header(
    src: &str,
    pos: usize,
) -> BmlResult<(Option<String>, String, usize, usize, usize)> {
    let mut pos = pos + "impl ".len();
    pos = skip_trivia(src, pos);
    let trait_: Option<String>;
    let target: String;
    if lookahead_impl_for(src, pos)? {
        let (t, p) = read_ident(src, pos)?;
        trait_ = Some(t);
        pos = skip_trivia(src, p);
        if !sw(src, pos, "for ") {
            return Err(shape("malformed impl"));
        }
        pos += 4;
        let (tg, p) = read_ident(src, pos)?;
        target = tg;
        pos = p;
    } else {
        trait_ = None;
        let (tg, p) = read_ident(src, pos)?;
        target = tg;
        pos = p;
    }
    pos = skip_trivia(src, pos);
    if at(src, pos) != Some(b'{') {
        return Err(shape("malformed impl body"));
    }
    let body_start = pos + 1;
    let body_end = matching_brace(src, pos);
    Ok((trait_, target, body_start, body_end, body_end + 1))
}

/// `_lookahead_impl_for`.
fn lookahead_impl_for(src: &str, pos: usize) -> BmlResult<bool> {
    let (_, after) = read_ident(src, pos)?;
    let after = skip_trivia(src, after);
    Ok(sw(src, after, "for "))
}

/// `_rskip_trivia`: move back over ASCII whitespace.
pub(crate) fn rskip_trivia(src: &str, mut pos: usize) -> usize {
    let b = src.as_bytes();
    while pos > 0 && matches!(b[pos - 1], b' ' | b'\t' | b'\r' | b'\n') {
        pos -= 1;
    }
    pos
}

/// `_collect_attrs_before`: attribute blocks immediately preceding `item_pos`.
pub(crate) fn collect_attrs_before(src: &str, item_pos: usize) -> Vec<String> {
    let b = src.as_bytes();
    let mut attrs: Vec<String> = Vec::new();
    let mut pos = rskip_trivia(src, item_pos);
    while pos > 0 {
        pos = rskip_trivia(src, pos);
        if pos == 0 {
            break;
        }
        if b[pos - 1] != b']' {
            let line_begin = line_start(src, pos - 1);
            let stripped = sub(src, line_begin, pos).trim();
            if stripped.starts_with("///") {
                break;
            }
            if stripped.starts_with("pub ") || stripped.starts_with("fn ") {
                break;
            }
            pos = line_begin;
            continue;
        }
        let close = pos - 1;
        let mut depth: i64 = 0;
        let mut open_idx: Option<usize> = None;
        let mut i = close as isize;
        while i >= 0 {
            let c = b[i as usize];
            if c == b']' {
                depth += 1;
            } else if c == b'[' {
                depth -= 1;
                if depth == 0 {
                    open_idx = Some(i as usize);
                    break;
                }
            }
            i -= 1;
        }
        let Some(open_idx) = open_idx else { break };
        if open_idx == 0 || b[open_idx - 1] != b'#' {
            break;
        }
        let start = open_idx - 1;
        attrs.insert(0, sub(src, start, close + 1).to_string());
        pos = start;
    }
    attrs
}

/// `_find_fn_body_start`: offset just past the `{` opening a fn body.
pub(crate) fn find_fn_body_start(src: &str, pos: usize) -> usize {
    let b = src.as_bytes();
    let mut depth_paren: i64 = 0;
    let mut depth_angle: i64 = 0;
    let mut i = pos;
    while i < b.len() {
        let ch = b[i];
        if ch == b'"' || ch == b'\'' {
            i = skip_rust_string(src, i);
            continue;
        }
        if ch == b'(' {
            depth_paren += 1;
        } else if ch == b')' {
            depth_paren -= 1;
        } else if ch == b'<' {
            depth_angle += 1;
        } else if ch == b'>' && depth_angle > 0 {
            depth_angle -= 1;
        } else if ch == b'{' && depth_paren == 0 && depth_angle == 0 {
            return i + 1;
        }
        i += 1;
    }
    b.len()
}

/// `_skip_item`.
pub(crate) fn skip_item(src: &str, pos: usize) -> BmlResult<usize> {
    let pos = skip_trivia(src, pos);
    if sw(src, pos, "use ") {
        return Ok(match find_from(src, pos, ";") {
            Some(semi) => semi + 1,
            None => src.len(),
        });
    }
    if sw(src, pos, "#[") {
        return Ok(matching_attr(src, pos));
    }
    if sw(src, pos, "impl ") {
        let (_, _, _, _, end) = parse_impl_header(src, pos)?;
        return Ok(end);
    }
    const DECLS: [&str; 7] = [
        "pub struct ",
        "struct ",
        "pub enum ",
        "pub fn ",
        "fn ",
        "pub const ",
        "const ",
    ];
    if DECLS.iter().any(|d| sw(src, pos, d)) {
        return skip_declaration(src, pos);
    }
    Ok(pos + 1)
}

/// `_skip_until_semicolon`.
pub(crate) fn skip_until_semicolon(src: &str, mut pos: usize) -> usize {
    let b = src.as_bytes();
    let mut depth_paren: i64 = 0;
    let mut depth_brace: i64 = 0;
    while pos < b.len() {
        let ch = b[pos];
        if ch == b'"' || ch == b'\'' {
            pos = skip_rust_string(src, pos);
            continue;
        }
        if depth_paren == 0 && depth_brace == 0 && ch == b';' {
            return pos;
        }
        if ch == b'(' {
            depth_paren += 1;
        } else if ch == b')' {
            depth_paren -= 1;
        } else if ch == b'{' {
            depth_brace += 1;
        } else if ch == b'}' {
            depth_brace -= 1;
        }
        pos += 1;
    }
    b.len()
}

/// `_skip_until_top_level`: first byte in `stop` at nesting depth zero.
pub(crate) fn skip_until_top_level(src: &str, mut pos: usize, stop: &str) -> usize {
    let b = src.as_bytes();
    let stop = stop.as_bytes();
    let mut depth_angle: i64 = 0;
    let mut depth_paren: i64 = 0;
    let mut depth_brace: i64 = 0;
    while pos < b.len() {
        let ch = b[pos];
        if ch == b'"' || ch == b'\'' {
            pos = skip_rust_string(src, pos);
            continue;
        }
        if depth_angle == 0 && depth_paren == 0 && depth_brace == 0 && stop.contains(&ch) {
            return pos;
        }
        if ch == b'<' {
            depth_angle += 1;
        } else if ch == b'>' && depth_angle > 0 {
            depth_angle -= 1;
        } else if ch == b'(' {
            depth_paren += 1;
        } else if ch == b')' {
            depth_paren -= 1;
        } else if ch == b'{' {
            depth_brace += 1;
        } else if ch == b'}' {
            depth_brace -= 1;
        }
        pos += 1;
    }
    b.len()
}

/// `_skip_function_decl`.
pub(crate) fn skip_function_decl(src: &str, pos: usize) -> BmlResult<usize> {
    let mut pos = skip_trivia(src, pos);
    if !sw(src, pos, "fn ") {
        return Err(shape("malformed function"));
    }
    pos += 3;
    let (_, p) = read_ident(src, pos)?;
    pos = skip_trivia(src, p);
    let b = src.as_bytes();
    if pos < b.len() && b[pos] == b'<' {
        pos = skip_balanced(src, pos, b'<', b'>');
    }
    if pos < b.len() && b[pos] == b'(' {
        pos = skip_balanced(src, pos, b'(', b')');
    }
    pos = skip_trivia(src, pos);
    if sw(src, pos, "->") {
        pos += 2;
        pos = skip_trivia(src, pos);
        pos = skip_until_top_level(src, pos, "{;");
    }
    pos = skip_trivia(src, pos);
    if at(src, pos) == Some(b';') {
        return Ok(pos + 1);
    }
    if at(src, pos) == Some(b'{') {
        return Ok(skip_balanced(src, pos, b'{', b'}'));
    }
    Ok(match find_from(src, pos, ";") {
        Some(semi) => semi + 1,
        None => src.len(),
    })
}

/// `_skip_const_item`.
fn skip_const_item(src: &str, pos: usize) -> BmlResult<usize> {
    let mut pos = skip_trivia(src, pos);
    if !sw(src, pos, "const ") {
        return Err(shape("malformed const"));
    }
    pos += "const ".len();
    let (_, p) = read_ident(src, pos)?;
    pos = skip_trivia(src, p);
    if at(src, pos) == Some(b':') {
        pos += 1;
        pos = skip_trivia(src, pos);
        pos = skip_until_top_level(src, pos, "=;");
    }
    pos = skip_trivia(src, pos);
    if at(src, pos) == Some(b'=') {
        pos += 1;
        pos = skip_until_semicolon(src, pos);
    }
    pos = skip_trivia(src, pos);
    if at(src, pos) == Some(b';') {
        return Ok(pos + 1);
    }
    Ok(src.len())
}

/// `_skip_type_decl`.
fn skip_type_decl(src: &str, pos: usize) -> BmlResult<usize> {
    let mut pos = skip_trivia(src, pos);
    if sw(src, pos, "pub ") {
        pos += 4;
        pos = skip_trivia(src, pos);
    }
    if sw(src, pos, "struct ") {
        pos += "struct ".len();
        let (_, p) = read_ident(src, pos)?;
        pos = skip_trivia(src, p);
        if at(src, pos) == Some(b'<') {
            pos = skip_balanced(src, pos, b'<', b'>');
        }
        pos = skip_trivia(src, pos);
        if at(src, pos) == Some(b';') {
            return Ok(pos + 1);
        }
        if at(src, pos) == Some(b'{') {
            return Ok(skip_balanced(src, pos, b'{', b'}'));
        }
        return Ok(pos);
    }
    if sw(src, pos, "enum ") {
        pos += "enum ".len();
        let (_, p) = read_ident(src, pos)?;
        pos = skip_trivia(src, p);
        if at(src, pos) == Some(b'<') {
            pos = skip_balanced(src, pos, b'<', b'>');
        }
        pos = skip_trivia(src, pos);
        if at(src, pos) == Some(b'{') {
            return Ok(skip_balanced(src, pos, b'{', b'}'));
        }
        return Ok(match find_from(src, pos, ";") {
            Some(semi) => semi + 1,
            None => src.len(),
        });
    }
    Err(shape("malformed type declaration"))
}

/// `_skip_declaration`.
pub(crate) fn skip_declaration(src: &str, pos: usize) -> BmlResult<usize> {
    let pos = skip_trivia(src, pos);
    if sw(src, pos, "pub ") {
        let after_pub = pos + 4;
        if sw(src, after_pub, "const fn ") {
            return skip_function_decl(src, after_pub + "const ".len());
        }
        if sw(src, after_pub, "fn ") {
            return skip_function_decl(src, after_pub);
        }
        if sw(src, after_pub, "const ") {
            return skip_const_item(src, after_pub);
        }
        if sw(src, after_pub, "struct ") || sw(src, after_pub, "enum ") {
            return skip_type_decl(src, pos);
        }
    }
    if sw(src, pos, "const fn ") {
        return skip_function_decl(src, pos + "const ".len());
    }
    if sw(src, pos, "const ") {
        return skip_const_item(src, pos);
    }
    if sw(src, pos, "fn ") {
        return skip_function_decl(src, pos);
    }
    if sw(src, pos, "struct ") || sw(src, pos, "enum ") {
        return skip_type_decl(src, pos);
    }
    Ok(match find_from(src, pos, ";") {
        Some(semi) => semi + 1,
        None => src.len(),
    })
}
