    let _ = std::panic::take_hook();
    assert!(known.iter().all(|k| !k.category.is_empty() && !k.reason.is_empty()), "every known entry needs a category and a reason");
    assert!(unexpected.is_empty() && stale.is_empty(), "\nunexpected differences ({}):\n{}\nstale entries ({}):\n{}", unexpected.len(), unexpected.join("\n"), stale.len(), stale.join("\n"));
