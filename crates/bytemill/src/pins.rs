//! The wire pin gate, porting `bps/pins.py`.

use crate::ast::ResolvedSchema;
use crate::emit_rstom::{packet_fields, parity_args, registry_entries};
use crate::errors::{BmlResult, emit, py_repr_str};
use crate::json::write_json_string;
use crate::minestom::Unit;

/// One pinned id-table entry (the Python `PinRow`): `cls` is the Minestom
/// class name, `hex` its BML-encoded reference bytes.
#[derive(Debug, Clone)]
pub struct PinRow {
    pub side: String,
    pub state: String,
    pub id: i128,
    pub cls: String,
    pub hex: String,
}

const GENERATED: &str = "bps/pins.py";

fn side_of(direction: &str) -> BmlResult<String> {
    match direction {
        "serverbound" => Ok("CLIENT".into()),
        "clientbound" => Ok("SERVER".into()),
        other => Err(emit(format!("KeyError: {}", py_repr_str(other)))),
    }
}

fn state_of(state: &str) -> BmlResult<String> {
    match state {
        "handshaking" => Ok("HANDSHAKE".into()),
        "status" => Ok("STATUS".into()),
        "login" => Ok("LOGIN".into()),
        "configuration" => Ok("CONFIGURATION".into()),
        "play" => Ok("PLAY".into()),
        other => Err(emit(format!("KeyError: {}", py_repr_str(other)))),
    }
}

fn sort_rows(rows: &mut [PinRow]) {
    rows.sort_by(|a, b| (&a.side, &a.state, a.id).cmp(&(&b.side, &b.state, b.id)));
}

/// `build_pins(resolved, units)`: one row per registry entry, sorted by (side, state, id).
pub fn build_pins(resolved: &ResolvedSchema, units: &[Unit]) -> BmlResult<Vec<PinRow>> {
    let mut rows = Vec::new();
    for (_, entries) in registry_entries(units).iter() {
        for (route, unit) in entries.iter() {
            let (fields, _) = packet_fields(&unit.pkt, resolved)?;
            let Some((_, bytes)) = parity_args(&unit.pkt, &fields, resolved)? else {
                return Err(emit(format!(
                    "packet {} has no pinned reference bytes",
                    py_repr_str(&unit.pkt.name)
                )));
            };
            rows.push(PinRow {
                side: side_of(&route.direction)?,
                state: state_of(&route.state)?,
                id: route.packet_id,
                cls: unit.cls.name.clone(),
                hex: hex(&bytes),
            });
        }
    }
    sort_rows(&mut rows);
    Ok(rows)
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// `pins_json(rows)`: the `wire_pins.json` text, without a trailing newline.
pub fn pins_json(rows: &[PinRow]) -> String {
    let mut sorted: Vec<PinRow> = rows.to_vec();
    sort_rows(&mut sorted);
    let body = sorted
        .iter()
        .map(|r| {
            let mut s = String::from("{\"side\":");
            write_json_string(&mut s, &r.side);
            s.push_str(",\"state\":");
            write_json_string(&mut s, &r.state);
            s.push_str(&format!(",\"id\":{}", r.id));
            s.push_str(",\"class\":");
            write_json_string(&mut s, &r.cls);
            s.push_str(",\"hex\":");
            write_json_string(&mut s, &r.hex);
            s.push('}');
            s
        })
        .collect::<Vec<_>>()
        .join(",\n");
    format!("{{\"_generated\": \"{GENERATED}\", \"rows\": [\n{body}\n]}}")
}

/// Whether on-disk JSON was written by `pins_json`.
pub fn pins_json_is_owned(text: &str) -> bool {
    text.contains(&format!("\"_generated\": \"{GENERATED}\""))
}

