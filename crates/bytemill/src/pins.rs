    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/bps");
    let pins: Pins = serde_json::from_str(&std::fs::read_to_string(format!("{dir}/wire_pins.json")).unwrap()).unwrap();
    let known: Vec<Known> = serde_json::from_str(&std::fs::read_to_string(format!("{dir}/wire_pins_known.json")).unwrap()).unwrap();
    let key = |s: &str, st: &str, id: i32| format!("{s}/{st}/{id}");
    let known_keys: BTreeSet<String> = known.iter().map(|k| key(&k.side, &k.state, k.id)).collect();

