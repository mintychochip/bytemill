static LAST_PANIC: Mutex<String> = Mutex::new(String::new());

fn clear_panic_slot() {
    *LAST_PANIC.lock().unwrap() = String::new();
}

fn panic_message(phase: &str) -> String {
    let detail = LAST_PANIC.lock().unwrap().clone();
    if detail.is_empty() {
        format!("{phase} panicked")
    } else {
        format!("{phase} panicked: {detail}")
    }
}

fn check(row: &Row) -> Result<(), String> {
    let info = registry(&row.side, &row.state)
        .packet_info(row.id)
        .map_err(|e| format!("no entry: {e:?}"))?;
    if info.simple_class_name() != row.class {
        return Err(format!("the table has {} here", info.simple_class_name()));
    }
    let bytes = hex::decode(&row.hex).expect("pin hex");
    let end = bytes.len() as i64;
    let mut buffer = NetworkBuffer::wrap(bytes.clone(), 0, end);
    clear_panic_slot();
    let value = catch_unwind(AssertUnwindSafe(|| info.serializer.read(&mut buffer)))
        .map_err(|_| panic_message("read"))?;
    if buffer.read_index() != end {
        return Err(format!("read {} of {end} bytes", buffer.read_index()));
    }
    clear_panic_slot();
    let written = catch_unwind(AssertUnwindSafe(|| {
        NetworkBuffer::make_array(|out| info.serializer.write(out, &value))
    }))
    .map_err(|_| panic_message("write"))?;
    if written != bytes {
        let at = written.iter().zip(&bytes).position(|(a, b)| a != b).unwrap_or(written.len().min(bytes.len()));
        return Err(format!("wrote {} bytes, pinned {}, first difference at {at}", written.len(), bytes.len()));
    }
    Ok(())
}

