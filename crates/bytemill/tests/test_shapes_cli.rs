//! Ports tests/test_shapes_cli.py: CLI `shapes extract` behaviour.
//!
//! Temp dirs use a pid + counter + nanos name (tests in one binary share a
//! pid) with an RAII guard so they vanish even on failure, like Python's
//! `TemporaryDirectory`. `load_ledger` only reads `*.json`, so the ledger
//! directory's `.gitkeep` never enters the byte comparison.

mod common;

use std::path::PathBuf;
use std::sync::atomic::{AtomicUsize, Ordering};

static TEMP_COUNTER: AtomicUsize = AtomicUsize::new(0);

struct TempDir {
    path: PathBuf,
}

impl TempDir {
    fn named(tag: &str) -> Self {
        let n = TEMP_COUNTER.fetch_add(1, Ordering::SeqCst);
        let path = std::env::temp_dir().join(format!(
            "bps-shapes-cli-{tag}-{}-{n}-{:?}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&path).unwrap();
        TempDir { path }
    }

    fn write(&self, rel: &str, text: &str) -> PathBuf {
        let path = self.path.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).unwrap();
        }
        std::fs::write(&path, text).unwrap();
        path
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

fn worktree_present() -> bool {
    common::rstom_tables::rstom_dir()
        .join("crates/rstom/src/network/packet")
        .is_dir()
}

/// Run the compiled `bml` like the Python tests spawn the CLI, keeping
/// stderr for failure messages.
fn run_cli(args: &[String]) -> (i32, String, String) {
    let out = std::process::Command::new(env!("CARGO_BIN_EXE_bml"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

const PROBE_PACKET: &str = "//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: probe\n\
    //! Port of `net.minestom.server.network.packet.server.play.ProbePacket`.\n\
    use std::sync::Arc;\n\
    use crate::network::packet::packet::Packet;\n\
    use crate::network::packet::serializer::{PacketSerializer, PacketValue};\n\
    use crate::network::packet::server::server_packet::{ServerPacket, ServerPacketGroup};\n\
    #[derive(Copy, Clone, Debug, PartialEq, Eq)]\n\
    pub struct ProbePacket { pub id: i32 }\n\
    impl ProbePacket {\n\
    \x20   pub fn new(id: i32) -> Self { Self { id } }\n\
    \x20   pub fn serializer() -> Arc<dyn PacketSerializer> { Arc::new(ProbePacketSerializer) }\n\
    }\n\
    impl Packet for ProbePacket {}\n\
    impl ServerPacket for ProbePacket {}\n\
    impl ServerPacketGroup for ProbePacket {}\n\
    struct ProbePacketSerializer;\n\
    impl PacketSerializer for ProbePacketSerializer {\n\
    \x20   fn write(&self, _b: &mut (), _v: &PacketValue) {}\n\
    \x20   fn read(&self, _b: &mut ()) -> PacketValue { Box::new(ProbePacket { id: 0 }) }\n\
    }\n";

#[test]
fn eligible_extract_sets_extras_from_ext_sibling() {
    let td = TempDir::named("extras");
    td.write(
        "ws/crates/rstom/src/network/packet/server/play/probe_packet.rs",
        PROBE_PACKET,
    );
    td.write(
        "ws/crates/rstom/src/network/packet/server/play/probe_packet.ext.rs",
        "//! Hand-written helpers for ProbePacket.\n",
    );
    let schema = td.write(
        "p.bps",
        &common::rstom_tables::probe_source(&common::repo_root(), "packet probe { id: i32be }"),
    );
    td.write(
        "ws/tools/packets_gen/schema/packets.json",
        &common::rstom_tables::probe_schema_json(),
    );
    let ws = td.path.join("ws");
    let out = td.path.join("shapes");
    std::fs::create_dir_all(&out).unwrap();
    let (code, _, stderr) = run_cli(&[
        "shapes".to_string(),
        "extract".to_string(),
        schema.to_string_lossy().into_owned(),
        "--rstom".to_string(),
        ws.to_string_lossy().into_owned(),
        "--eligible".to_string(),
        "--out".to_string(),
        out.to_string_lossy().into_owned(),
    ]);
    assert_eq!(code, 0, "{stderr}");
    let shape_path = out.join("server/play/probe_packet.json");
    assert!(
        shape_path.is_file(),
        "shape not written: {}",
        shape_path.display()
    );
    let shape =
        bytemill::shapes::shape_from_json(&std::fs::read_to_string(&shape_path).unwrap()).unwrap();
    assert_eq!(shape.extras.as_deref(), Some("probe_packet.ext.rs"));
}

#[test]
fn worktree_extract_matches_committed_ledger_bytes() {
    if !worktree_present() {
        eprintln!("skipped: rstom worktree not present");
        return;
    }
    let shapes_dir = common::repo_root().join("targets/rstom/shapes");
    let ledger = bytemill::shapes::load_ledger(&shapes_dir).unwrap();
    assert_eq!(ledger.len(), 64);
    let td = TempDir::named("ledger");
    let out = td.path.join("extracted");
    let (code, _, stderr) = run_cli(&[
        "shapes".to_string(),
        "extract".to_string(),
        common::schema_path("minecraft_26_3_wiki.bps")
            .to_string_lossy()
            .into_owned(),
        "--rstom".to_string(),
        common::rstom_tables::rstom_dir()
            .to_string_lossy()
            .into_owned(),
        "--out".to_string(),
        out.to_string_lossy().into_owned(),
    ]);
    assert_eq!(code, 0, "{stderr}");
    let mut mismatches = Vec::new();
    for (module, _) in &ledger {
        let committed = shapes_dir.join(format!("{module}.json"));
        let extracted = out.join(format!("{module}.json"));
        if !extracted.is_file() {
            mismatches.push(format!("{module}: not extracted"));
            continue;
        }
        if std::fs::read(&committed).unwrap() != std::fs::read(&extracted).unwrap() {
            mismatches.push(format!("{module}: byte mismatch"));
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} mismatches: {:?}",
        mismatches.len(),
        &mismatches[..mismatches.len().min(5)]
    );
}
