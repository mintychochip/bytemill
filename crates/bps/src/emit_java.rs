/// Cursor over a byte array; short reads throw [`BpsError`].
const READER_JAVA: &str = r#"// Generated by bpsc from a BPS binary-protocol schema. Do not edit.
public class Reader {
    private final byte[] data;
    private int pos;

    public Reader(byte[] data) {
        this.data = data;
        this.pos = 0;
    }

    public int remaining() {
        return data.length - pos;
    }

    private void need(int n) {
        if (data.length - pos < n) {
            throw new BpsError("short buffer at offset " + pos);
        }
    }

    public int readU8() {
        need(1);
        return data[pos++] & 0xFF;
    }

    public int peekU8() {
        need(1);
        return data[pos] & 0xFF;
    }

    public void skip(int n) {
        if (n < 0) {
            throw new BpsError("negative skip at offset " + pos);
        }
        need(n);
        pos += n;
    }

    public float readF32() {
        need(4);
        int bits = ((data[pos] & 0xFF) << 24)
            | ((data[pos + 1] & 0xFF) << 16)
            | ((data[pos + 2] & 0xFF) << 8)
            | (data[pos + 3] & 0xFF);
        pos += 4;
        return Float.intBitsToFloat(bits);
    }

    public double readF64() {
        need(8);
        long bits = ((long) (data[pos] & 0xFF) << 56)
            | ((long) (data[pos + 1] & 0xFF) << 48)
            | ((long) (data[pos + 2] & 0xFF) << 40)
            | ((long) (data[pos + 3] & 0xFF) << 32)
            | ((long) (data[pos + 4] & 0xFF) << 24)
            | ((long) (data[pos + 5] & 0xFF) << 16)
            | ((long) (data[pos + 6] & 0xFF) << 8)
            | (data[pos + 7] & 0xFF);
        pos += 8;
        return Double.longBitsToDouble(bits);
    }

    public byte[] readBytes(int n) {
        if (n < 0) {
            throw new BpsError("negative length at offset " + pos);
        }
        need(n);
        byte[] out = java.util.Arrays.copyOfRange(data, pos, pos + n);
        pos += n;
        return out;
    }

    public byte[] readRest() {
        byte[] out = java.util.Arrays.copyOfRange(data, pos, data.length);
        pos = data.length;
        return out;
    }
}
"#;

/// A growing byte buffer; overlong fixed writes throw [`BpsError`].
const WRITER_JAVA: &str = r#"// Generated by bpsc from a BPS binary-protocol schema. Do not edit.
public class Writer {
    private final java.io.ByteArrayOutputStream buf = new java.io.ByteArrayOutputStream();

    public void writeU8(int v) {
        buf.write(v & 0xFF);
    }

    public void writeF32(float v) {
        int bits = Float.floatToIntBits(v);
        buf.write((bits >>> 24) & 0xFF);
        buf.write((bits >>> 16) & 0xFF);
        buf.write((bits >>> 8) & 0xFF);
        buf.write(bits & 0xFF);
    }

    public void writeF64(double v) {
        long bits = Double.doubleToLongBits(v);
        buf.write((int) ((bits >>> 56) & 0xFF));
        buf.write((int) ((bits >>> 48) & 0xFF));
        buf.write((int) ((bits >>> 40) & 0xFF));
        buf.write((int) ((bits >>> 32) & 0xFF));
        buf.write((int) ((bits >>> 24) & 0xFF));
        buf.write((int) ((bits >>> 16) & 0xFF));
        buf.write((int) ((bits >>> 8) & 0xFF));
        buf.write((int) (bits & 0xFF));
    }

    public void writeBytes(byte[] v) {
        buf.write(v, 0, v.length);
    }

    public void writeFixed(byte[] v, int n) {
        if (v.length > n) {
            throw new BpsError("bytes too long");
        }
        writeBytes(v);
        for (int i = v.length; i < n; i++) {
            buf.write(0);
        }
    }

    public byte[] toByteArray() {
        return buf.toByteArray();
    }
}
"#;

