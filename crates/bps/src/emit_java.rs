/// `emit java`: write the `bpsgen` package for the default Java version.
pub fn emit_java(resolved: &ResolvedSchema, out_dir: &Path) -> BpsResult<()> {
    emit_java_with_version(resolved, out_dir, JavaVersion::default())
}

/// `emit java`: write the `bpsgen` package for `ver`.
pub fn emit_java_with_version(
    resolved: &ResolvedSchema,
    out_dir: &Path,
    ver: JavaVersion,
) -> BpsResult<()> {
    let program = crate::ir::typed(resolved)?;
    let printer = Printer::new(&program, ver);
    let dir = out_dir.join("bpsgen");
    fs::create_dir_all(&dir).map_err(|e| emit(e.to_string()))?;
    write_file(&dir, "Reader.java", READER_JAVA)?;
    write_file(&dir, "Writer.java", WRITER_JAVA)?;
    write_file(&dir, "BpsError.java", BPS_ERROR_JAVA)?;
    write_file(&dir, "BpsUtil.java", BPS_UTIL_JAVA)?;
    for (stem, body) in printer.stem_files()? {
        write_file(&dir, &format!("{stem}.java"), &body)?;
    }
    Ok(())
}

fn write_file(dir: &Path, name: &str, contents: &str) -> BpsResult<()> {
    fs::write(dir.join(name), contents).map_err(|e| emit(e.to_string()))
}

