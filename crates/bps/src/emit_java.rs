impl BodyGen<'_> {
    /// The payload of a sum variant as a value expression.
    fn variant_value(
        &mut self,
        ty: TypeIdx,
        variant: VariantIdx,
        payload: Option<&Expr>,
    ) -> BpsResult<String> {
        if self.data.direct.contains(&(ty, variant)) {
            match payload {
                Some(value) => self.expr(value),
                None => Err(emit(
                    "emit java: direct variant without payload".to_string(),
                )),
            }
        } else {
            let wrap = self.data.wrappers[&(ty, variant)].clone();
            let wrap_ref = if self.data.type_owner[ty] == self.owner {
                wrap
            } else {
                format!("{o}.{wrap}", o = self.data.type_owner[ty])
            };
            match payload {
                None => Ok(format!("new {wrap_ref}()")),
                Some(value) => {
                    let prog = self.data.prog;
                    let text = self.expr(value)?;
                    let (vty, vopt) = prog.expr_ty(self.body, value);
                    let pty = match &prog.types[ty].kind {
                        TypeKind::Sum { variants } => &variants[variant].payload,
                        _ => {
                            return Err(emit("emit java: Variant of a non-sum".to_string()));
                        }
                    };
                    match pty {
                        Some(pty) => {
                            let coerced = self.coerce_ty(text, &vty, vopt, pty, false)?;
                            Ok(format!("new {wrap_ref}({coerced})"))
                        }
                        None => Err(emit("emit java: payload for a unit variant".to_string())),
                    }
                }
            }
        }
    }
    /// A record value.
    fn construct_java(&mut self, ty: TypeIdx, fields: &[Expr]) -> BpsResult<String> {
        let prog = self.data.prog;
        let decls = match &prog.types[ty].kind {
            TypeKind::Record { fields } => fields,
            _ => return Err(emit("emit java: Construct of a non-record".to_string())),
        };
        let target = self.data.type_ref(self.data.resolve(ty), &self.owner);
        let mut parts = Vec::with_capacity(fields.len());
        for (decl, value) in decls.iter().zip(fields.iter()) {
            let text = self.expr(value)?;
            let (vty, vopt) = prog.expr_ty(self.body, value);
            parts.push(self.coerce_ty(text, &vty, vopt, &decl.ty, decl.optional)?);
        }
        Ok(format!("new {target}({})", parts.join(", ")))
    }

    /// A conditional branch as the conditional's type.
    fn coerce_branch(&mut self, branch: &Expr, want: &Ty) -> BpsResult<String> {
        let text = self.expr(branch)?;
        let prog = self.data.prog;
        let (got, gopt) = prog.expr_ty(self.body, branch);
        let base = if gopt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &got, want)
    }

    /// A binary operand coerced to the operator's result type.
    fn coerce_operand(&mut self, side: &Expr, want: &Ty) -> BpsResult<String> {
        let text = self.expr(side)?;
        let prog = self.data.prog;
        let (got, gopt) = prog.expr_ty(self.body, side);
        let base = if gopt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &got, want)
    }

    /// Print a binary operand, parenthesizing when Java would parse it
    /// differently. Mismatched operand widths carry explicit casts from the
    /// program, so only precedence needs parentheses here.
    fn operand(&mut self, child: &Expr, level: u8, is_right: bool) -> BpsResult<String> {
        let need = match child {
            Expr::Binary { op: child_op, .. } => {
                let child_level = prec(*child_op);
                // The right side is parenthesized at equal precedence:
                // `a - (b - c)` must not collapse to `a - b - c`.
                child_level < level || (is_right && child_level == level)
            }
            Expr::Cond { .. } => false,
            _ => false,
        };
        if need {
            Ok(format!("({})", self.expr(child)?))
        } else {
            self.expr(child)
        }
    }

    /// `==` / `!=`, with value comparison for strings, bytes, and objects.
    fn equality(&mut self, op: BinOp, lhs: &Expr, rhs: &Expr) -> BpsResult<String> {
        let prog = self.data.prog;
        let (lty, lopt) = prog.expr_ty(self.body, lhs);
        let (rty, ropt) = prog.expr_ty(self.body, rhs);
        let l = self.operand(lhs, prec(BinOp::Eq), false)?;
        let r = self.operand(rhs, prec(BinOp::Eq), true)?;
        if lopt || ropt {
            let base = format!("Objects.equals({l}, {r})");
            return Ok(if op == BinOp::Eq {
                base
            } else {
                format!("!({base})")
            });
        }
        let base = match (base_kind(prog, &lty), base_kind(prog, &rty)) {
            (BaseKind::Num | BaseKind::Bool, BaseKind::Num | BaseKind::Bool) => {
                format!("{l} == {r}")
            }
            (BaseKind::Str, BaseKind::Str) => format!("{l}.equals({r})"),
            (BaseKind::Bytes, BaseKind::Bytes) => format!("Arrays.equals({l}, {r})"),
            _ => format!("Objects.equals({l}, {r})"),
        };
        Ok(if op == BinOp::Eq {
            base
        } else {
            format!("!({base})")
        })
    }

    fn binary(
        &mut self,
        op: BinOp,
        lhs: &Expr,
        rhs: &Expr,
        ty: &Ty,
        _wraps: bool,
    ) -> BpsResult<String> {
        let prog = self.data.prog;
        let jt = self.data.base_java(ty, &self.owner)?;
        // Signed division and modulo floor; Java truncates. Use a helper when
        // the dividend may be negative.
        let negative = match ty {
            Ty::Int(t) if t.signed() => match prog.int_range(self.body, lhs) {
                Some((lo, _)) => lo < 0,
                None => true,
            },
            _ => false,
        };
        if negative && matches!(op, BinOp::Div | BinOp::Mod) {
            let helper = if op == BinOp::Div {
                "Math.floorDiv"
            } else {
                "Math.floorMod"
            };
            // `Math` has no byte/short overloads: compute in `int`.
            let arg_ty: Ty = if jt == "byte" || jt == "short" {
                Ty::Int(IntTy::I32)
            } else {
                ty.clone()
            };
            let left = self.coerce_operand(lhs, &arg_ty)?;
            let right = self.coerce_operand(rhs, &arg_ty)?;
            let call = format!("{helper}({left}, {right})");
            let arg_jt = self.data.base_java(&arg_ty, &self.owner)?;
            if arg_jt == jt {
                return Ok(call);
            }
            return Ok(format!("({jt})({call})"));
        }
        if matches!(op, BinOp::Eq | BinOp::Ne) {
            return self.equality(op, lhs, rhs);
        }
        if matches!(op, BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge) {
            let (lty, _) = prog.expr_ty(self.body, lhs);
            let (rty, _) = prog.expr_ty(self.body, rhs);
            if base_kind(prog, &lty) != BaseKind::Num || base_kind(prog, &rty) != BaseKind::Num {
                return Err(emit("emit java: ordering on non-numbers".to_string()));
            }
        }
        let level = prec(op);
        let left = match lhs {
            Expr::Int { value, ty } if hex_literal(op, *value) => {
                int_java(*ty)?;
                mask_operand(*value)
            }
            _ => self.operand(lhs, level, false)?,
        };
        let right = match rhs {
            Expr::Int { value, ty } if hex_literal(op, *value) => {
                int_java(*ty)?;
                mask_operand(*value)
            }
            _ => self.operand(rhs, level, true)?,
        };
        Ok(format!("{left} {symbol} {right}", symbol = op.symbol()))
    }

    fn expr(&mut self, expr: &Expr) -> BpsResult<String> {
        match expr {
            Expr::Int { value, ty } => {
                int_java(*ty)?;
                Ok(int_lit(i128::from(*value))?)
            }
            Expr::Bool(value) => Ok(value.to_string()),
            Expr::Str(value) => Ok(java_quote(value)),
            Expr::Local(id) => {
                if self.value_this == Some(*id) {
                    Ok("this".to_string())
                } else {
                    Ok(self.local_java[*id].clone())
                }
            }
            Expr::Field { base, ty, field } => {
                let fname = match &self.data.prog.types[*ty].kind {
                    TypeKind::Record { fields } => match fields.get(*field) {
                        Some(decl) => field_java(&decl.name),
                        None => return Err(emit("emit java: unknown field".to_string())),
                    },
                    _ => return Err(emit("emit java: Field of a non-record".to_string())),
                };
                let text = self.expr(base)?;
                if self.data.ver.supports_records() {
                    Ok(format!("{text}.{fname}()"))
                } else {
                    Ok(format!("{text}.{}()", getter(&fname)))
                }
            }
            Expr::Present(inner) => {
                let prog = self.data.prog;
                let (_, opt) = prog.expr_ty(self.body, inner);
                if !opt {
                    return Ok("true".to_string());
                }
                let text = self.expr(inner)?;
                Ok(format!("{text}.isPresent()"))
            }
            Expr::Get(inner) => {
                let prog = self.data.prog;
                let (_, opt) = prog.expr_ty(self.body, inner);
                let text = self.expr(inner)?;
                if opt {
                    Ok(format!("{text}.get()"))
                } else {
                    Ok(text)
                }
            }
            Expr::Not(inner) => {
                let prog = self.data.prog;
                let (ty, _) = prog.expr_ty(self.body, inner);
                let text = self.expr(inner)?;
                if matches!(ty, Ty::Bool) {
                    if is_atomic(inner) {
                        Ok(format!("!{text}"))
                    } else {
                        Ok(format!("!({text})"))
                    }
                } else {
                    Ok(format!("({text} == 0)"))
                }
            }
            Expr::Binary {
                op,
                lhs,
                rhs,
                ty,
                wraps,
            } => self.binary(*op, lhs, rhs, ty, *wraps),
            Expr::Cond {
                cond,
                then,
                els,
                ty,
            } => {
                let jt = self.data.base_java(ty, &self.owner)?;
                let c = self.expr(cond)?;
                let t = self.coerce_branch(then, ty)?;
                let e = self.coerce_branch(els, ty)?;
                let out = format!("({c} ? {t} : {e})");
                // A ternary of two bytes is an `int`: cast narrow results.
                if jt == "byte" || jt == "short" {
                    Ok(format!("({jt}){out}"))
                } else {
                    Ok(out)
                }
            }
            Expr::Cast { expr, to } => {
                let want = self.data.base_java(to, &self.owner)?;
                let prog = self.data.prog;
                let (from, from_opt) = prog.expr_ty(self.body, expr);
                let text = self.expr(expr)?;
                let base = if from_opt {
                    format!("{text}.get()")
                } else {
                    text
                };
                // A widening cast is elided; the inner expression keeps its
                // own precedence, so a binary must stay parenthesized under
                // whichever operator encloses the cast.
                let elided = || {
                    if matches!(expr.as_ref(), Expr::Binary { .. }) {
                        format!("({base})")
                    } else {
                        base.clone()
                    }
                };
                let from_jt = self.data.base_java(&from, &self.owner)?;
                if from_jt == want {
                    return Ok(elided());
                }
                match (&from, to) {
                    (Ty::Bool, Ty::Int(_)) => {
                        let v = format!("({base} ? 1 : 0)");
                        if want == "byte" || want == "short" {
                            Ok(format!("({want}){v}"))
                        } else {
                            Ok(v)
                        }
                    }
                    (Ty::Int(_), Ty::Int(_))
                    | (Ty::F32, Ty::F64)
                    | (Ty::F64, Ty::F32)
                    | (Ty::Named(_), Ty::Int(_))
                    | (Ty::Int(_), Ty::Named(_))
                    | (Ty::Named(_), Ty::Named(_)) => {
                        if matches!(from, Ty::Named(_)) && matches!(to, Ty::Named(_)) {
                            return Err(emit(format!(
                                "emit java: unsupported cast {from_jt} to {want}"
                            )));
                        }
                        // Java re-associates a widened operand at the narrow
                        // type (`int << 56` truncates), so a widening cast is
                        // always spelled unless the types already agree.
                        Ok(format!("({want})({base})"))
                    }
                    _ => Err(emit(format!(
                        "emit java: unsupported cast {from_jt} to {want}"
                    ))),
                }
            }
            Expr::Call { func, args } => match func {
                Func::SignExtend => {
                    let value = self.as_long(&args[0])?;
                    let bits = self.as_int(&args[1])?;
                    Ok(format!("BpsUtil.signExtend({value}, {bits})"))
                }
                Func::Utf16Units => {
                    let text = self.expr(&args[0])?;
                    Ok(format!(
                        "({recv}).length()",
                        recv = utf_recv(&text, self, &args[0])?
                    ))
                }
                Func::Utf8Len => {
                    let text = self.expr(&args[0])?;
                    let recv = utf_recv(&text, self, &args[0])?;
                    Ok(format!(
                        "(long) ({recv}).getBytes(StandardCharsets.UTF_8).length"
                    ))
                }
                Func::StrLen => {
                    let text = self.expr(&args[0])?;
                    let recv = utf_recv(&text, self, &args[0])?;
                    Ok(format!(
                        "(long) ({recv}).codePointCount(0, ({recv}).length())"
                    ))
                }
                Func::BytesLen => {
                    let text = self.expr(&args[0])?;
                    let recv = utf_recv(&text, self, &args[0])?;
                    Ok(format!("(long) ({recv}).length"))
                }
                Func::ListLen => {
                    let text = self.expr(&args[0])?;
                    let prog = self.data.prog;
                    let (_, opt) = prog.expr_ty(self.body, &args[0]);
                    if opt {
                        Ok(format!("(long) ({text}).get().size()"))
                    } else {
                        Ok(format!("(long) ({text}).size()"))
                    }
                }
                Func::Min => {
                    let low = self.as_long(&args[0])?;
                    let high = self.as_long(&args[1])?;
                    Ok(format!("Math.min({low}, {high})"))
                }
                Func::Max => {
                    let low = self.as_long(&args[0])?;
                    let high = self.as_long(&args[1])?;
                    Ok(format!("Math.max({low}, {high})"))
                }
            },
            Expr::StrBytes(inner) => {
                let text = self.expr(inner)?;
                Ok(format!("({text}).getBytes(StandardCharsets.UTF_8)"))
            }
            Expr::Remaining => {
                if !self.is_decode {
                    return Err(emit("emit java: Remaining in encode".to_string()));
                }
                Ok(format!("{cur}.remaining()", cur = self.cursor.clone()))
            }
            Expr::Construct { ty, fields } => self.construct_java(*ty, fields),
            Expr::Variant {
                ty,
                variant,
                payload,
            } => self.variant_value(*ty, *variant, payload.as_deref()),
        }
    }
}

/// The receiver of a string/bytes builtin: appended with `.get()` when the
/// argument is optional.
fn utf_recv(text: &str, bg: &BodyGen<'_>, arg: &Expr) -> BpsResult<String> {
    let (_, opt) = bg.data.prog.expr_ty(bg.body, arg);
    Ok(if opt {
        format!("{text}.get()")
    } else {
        text.to_string()
    })
}

/// The value kind of an equality operand: numbers and booleans compare with
/// `==`, strings, bytes, and objects compare by value.
#[derive(Clone, Copy, PartialEq, Eq)]
enum BaseKind {
    Num,
    Bool,
    Str,
    Bytes,
    Other,
}

fn base_kind(prog: &Program, ty: &Ty) -> BaseKind {
    match ty {
        Ty::Int(_) | Ty::F32 | Ty::F64 => BaseKind::Num,
        Ty::Bool => BaseKind::Bool,
        Ty::Str => BaseKind::Str,
        Ty::Bytes => BaseKind::Bytes,
        Ty::List(_) => BaseKind::Other,
        Ty::Named(t) => {
            let mut r = *t;
            loop {
                match &prog.types[r].kind {
                    TypeKind::Alias { target } => r = *target,
                    TypeKind::Enum { .. } => return BaseKind::Num,
                    _ => return BaseKind::Other,
                }
            }
        }
    }
}

/// Java precedence levels for binary operators (tighter binds higher).
fn prec(op: BinOp) -> u8 {
    match op {
        BinOp::Or => 1,
        BinOp::And => 2,
        BinOp::BitOr => 3,
        BinOp::BitXor => 4,
        BinOp::BitAnd => 5,
        BinOp::Eq | BinOp::Ne => 6,
        BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => 7,
        BinOp::Shl | BinOp::Shr => 8,
        BinOp::Add | BinOp::Sub => 9,
        BinOp::Mul | BinOp::Div | BinOp::Mod => 10,
    }
}

/// Expressions that need no parentheses under `!`.
fn is_atomic(expr: &Expr) -> bool {
    matches!(
        expr,
        Expr::Local(_)
            | Expr::Bool(_)
            | Expr::Int { .. }
            | Expr::Str(_)
            | Expr::Present(_)
            | Expr::Get(_)
            | Expr::Field { .. }
    )
}
