/// Java type for an integer class; unsigned values live in the next-wider
/// signed type so comparisons need no masking. `I128` never appears in
/// shipped schemas.
fn int_java(ty: IntTy) -> BpsResult<&'static str> {
    match ty {
        IntTy::I8 => Ok("byte"),
        IntTy::I16 => Ok("short"),
        IntTy::I32 => Ok("int"),
        IntTy::I64 => Ok("long"),
        IntTy::U8 => Ok("int"),
        IntTy::U16 => Ok("int"),
        IntTy::U32 => Ok("long"),
        IntTy::U64 => Ok("long"),
        IntTy::I128 => Err(emit("emit java: i128 has no Java type".to_string())),
    }
}

fn boxed(base: &str) -> &str {
    match base {
        "byte" => "Byte",
        "short" => "Short",
        "int" => "Integer",
        "long" => "Long",
        "boolean" => "Boolean",
        "float" => "Float",
        "double" => "Double",
        _ => base,
    }
}

fn numeric_rank(base: &str) -> Option<u32> {
    match base {
        "byte" => Some(0),
        "short" => Some(1),
        "int" => Some(2),
        "long" => Some(3),
        "float" => Some(4),
        "double" => Some(5),
        _ => None,
    }
}

impl Data<'_> {
    /// The unboxed Java type of `ty` against `owner` (aliases and enums
    /// resolved).
    fn base_java(&self, ty: &Ty, owner: &str) -> BpsResult<String> {
        match ty {
            Ty::Int(t) => Ok(int_java(*t)?.to_string()),
            Ty::Bool => Ok("boolean".to_string()),
            Ty::F32 => Ok("float".to_string()),
            Ty::F64 => Ok("double".to_string()),
            Ty::Str => Ok("String".to_string()),
            Ty::Bytes => Ok("byte[]".to_string()),
            Ty::List(inner) => Ok(format!("List<{}>", boxed(&self.base_java(inner, owner)?))),
            Ty::Named(t) => {
                let r = self.resolve(*t);
                match &self.prog.types[r].kind {
                    TypeKind::Enum { base, .. } => Ok(int_java(*base)?.to_string()),
                    _ => Ok(self.type_ref(r, owner)),
                }
            }
        }
    }

    /// The Java type of `ty`, resolved against `owner`; `optional` wraps in
    /// `Optional`.
    fn java_ty(&self, ty: &Ty, optional: bool, owner: &str) -> BpsResult<String> {
        let base = self.base_java(ty, owner)?;
        Ok(if optional {
            format!("Optional<{}>", boxed(&base))
        } else {
            base
        })
    }

    /// The zero a local of this type starts at.
    fn zero(&self, ty: &Ty, optional: bool, _owner: &str) -> BpsResult<String> {
        if optional {
            return Ok("Optional.empty()".to_string());
        }
        match ty {
            Ty::Int(t) => Ok(match int_java(*t)? {
                "long" => "0L",
                "byte" => "(byte) 0",
                "short" => "(short) 0",
                _ => "0",
            }
            .to_string()),
            Ty::Bool => Ok("false".to_string()),
            Ty::F32 => Ok("0.0f".to_string()),
            Ty::F64 => Ok("0.0".to_string()),
            Ty::Str => Ok("\"\"".to_string()),
            Ty::Bytes => Ok("new byte[0]".to_string()),
            Ty::List(_) => Ok("new ArrayList<>()".to_string()),
            Ty::Named(t) => {
                let r = self.resolve(*t);
                match &self.prog.types[r].kind {
                    TypeKind::Enum { base, .. } => Ok(match int_java(*base)? {
                        "long" => "0L",
                        "byte" => "(byte) 0",
                        "short" => "(short) 0",
                        _ => "0",
                    }
                    .to_string()),
                    _ => Ok("null".to_string()),
                }
            }
        }
    }
}

/// The Java field name of a record field (an `Object` method takes `_`).
fn field_java(name: &Name) -> String {
    let base = camel(name);
    if OBJECT_METHODS.contains(&base.as_str()) {
        format!("{base}_")
    } else {
        base
    }
}

/// The getter of a Java 8 class field: `n` is `getN`.
fn getter(field: &str) -> String {
    format!("get{head}", head = cap_first(field))
}

