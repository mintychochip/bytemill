fn cap_first(word: &str) -> String {
    let mut chars = word.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// PascalCase with keyword escaping.
fn pascal(name: &Name) -> String {
    let mut out = String::new();
    for word in name.words() {
        out.push_str(&cap_first(word));
    }
    escape(out, JAVA_KEYWORDS)
}

/// camelCase with keyword escaping.
fn camel(name: &Name) -> String {
    let mut out = String::new();
    for (i, word) in name.words().iter().enumerate() {
        if i == 0 {
            out.push_str(word);
        } else {
            out.push_str(&cap_first(word));
        }
    }
    escape(out, JAVA_KEYWORDS)
}

/// A Java double-quoted string literal.
fn java_quote(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The wrapper class for an output stem: `play_clientbound` is
/// `PlayClientbound`.
fn stem_class(stem: &str) -> String {
    let mut out = String::new();
    for piece in stem.split('_') {
        out.push_str(&cap_first(piece));
    }
    if out.is_empty() {
        out.push('X');
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn claim_name(taken: &mut BTreeSet<String>, base: &str) -> String {
    let mut name = base.to_string();
    let mut n = 2_u32;
    while taken.contains(&name) {
        name = format!("{base}{n}");
        n += 1;
    }
    taken.insert(name.clone());
    name
}

