/// One function body under emission.
struct BodyGen<'a> {
    data: &'a Data<'a>,
    body: &'a Body,
    codec_snake: String,
    is_decode: bool,
    owner: String,
    cursor: String,
    local_java: Vec<String>,
    taken: BTreeSet<String>,
    /// Locals bound by `for` loops: declared by the loop, not up front.
    foreach_items: BTreeSet<usize>,
    /// The encode value local prints as `this` (a record's own `encode`).
    value_this: Option<LocalId>,
    /// The codec value type a decode returns.
    ret_ty: Option<Ty>,
    out: String,
    indent: usize,
}

impl<'a> BodyGen<'a> {
    fn new(
        data: &'a Data<'a>,
        body: &'a Body,
        codec_snake: &str,
        is_decode: bool,
        owner: &str,
    ) -> BodyGen<'a> {
        let mut taken = BTreeSet::new();
        let local_java = body
            .locals
            .iter()
            .map(|l| camel(&l.name))
            .collect::<Vec<_>>();
        for name in &local_java {
            taken.insert(name.clone());
        }
        let mut foreach_items = BTreeSet::new();
        collect_foreach(&body.stmts, &mut foreach_items);
        let mut bg = BodyGen {
            data,
            body,
            codec_snake: codec_snake.to_string(),
            is_decode,
            owner: owner.to_string(),
            cursor: String::new(),
            local_java,
            taken,
            foreach_items,
            value_this: None,
            ret_ty: None,
            out: String::new(),
            indent: 2,
        };
        bg.cursor = bg.pick(if is_decode { "r" } else { "w" });
        bg
    }

    /// An unused identifier based on `base`.
    fn pick(&mut self, base: &str) -> String {
        let mut name = base.to_string();
        let mut n = 2_u32;
        while self.taken.contains(&name) {
            name = format!("{base}{n}");
            n += 1;
        }
        self.taken.insert(name.clone());
        name
    }

    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn open(&mut self, text: &str) {
        self.line(&format!("{text} {{"));
        self.indent += 1;
    }

    fn close(&mut self) {
        self.indent -= 1;
        self.line("}");
    }

    /// `stmts` as the body of an `if`, `else`, or loop: one indent deeper.
    fn block(&mut self, stmts: &[Stmt]) -> BpsResult<()> {
        self.indent += 1;
        let result = self.stmts(stmts);
        self.indent -= 1;
        result
    }

    fn stmts(&mut self, stmts: &[Stmt]) -> BpsResult<()> {
        for stmt in stmts {
            // `Declare` is covered by the upfront declarations below.
            if !matches!(stmt, Stmt::Declare { .. }) {
                self.stmt(stmt)?;
            }
        }
        Ok(())
    }

    /// The whole method body: upfront locals, statements, and the
    /// unreachable tail of a decode.
    fn body_text(&mut self) -> BpsResult<String> {
        for (i, local) in self.body.locals.iter().enumerate() {
            if self.body.params.contains(&i) {
                continue;
            }
            if !self.is_decode && self.body.value == Some(i) {
                continue;
            }
            if self.foreach_items.contains(&i) {
                continue;
            }
            let ty = self.data.java_ty(&local.ty, local.optional, &self.owner)?;
            let zero = self.data.zero(&local.ty, local.optional, &self.owner)?;
            let name = self.local_java[i].clone();
            self.line(&format!("{ty} {name} = {zero};"));
        }
        let body = self.body;
        self.stmts(&body.stmts)?;
        if self.is_decode && !diverges(&self.body.stmts) {
            let snake = self.codec_snake.clone();
            self.line(&format!(
                "throw new BpsError({message});",
                message = java_quote(&format!("{snake}: unreachable"))
            ));
        }
        Ok(std::mem::take(&mut self.out))
    }

    fn fail(&self, detail: &str) -> String {
        format!(
            "throw new BpsError({message});",
            message = java_quote(&format!("{codec}: {detail}", codec = self.codec_snake))
        )
    }

    /// `expr` coerced to a value of the local's type.
    fn store(&self, text: String, from_ty: &Ty, from_opt: bool, dst: LocalId) -> BpsResult<String> {
        let local = &self.body.locals[dst];
        self.coerce_ty(text, from_ty, from_opt, &local.ty, local.optional)
    }

    fn coerce_ty(
        &self,
        text: String,
        from_ty: &Ty,
        from_opt: bool,
        to_ty: &Ty,
        to_opt: bool,
    ) -> BpsResult<String> {
        if from_opt && !to_opt {
            let base = format!("{text}.get()");
            return self.prim_coerce(base, from_ty, to_ty);
        }
        if !from_opt && to_opt {
            return Ok(format!("Optional.of({text})"));
        }
        if from_opt && to_opt {
            return Ok(text);
        }
        self.prim_coerce(text, from_ty, to_ty)
    }

    /// `base` (of Java type `from_ty`) as `to_ty`: implicit when widening, an
    /// explicit cast when narrowing.
    fn prim_coerce(&self, base: String, from_ty: &Ty, to_ty: &Ty) -> BpsResult<String> {
        let from = self.data.base_java(from_ty, &self.owner)?;
        let to = self.data.base_java(to_ty, &self.owner)?;
        if from == to {
            return Ok(base);
        }
        if from == "boolean" {
            let v = format!("({base} ? 1 : 0)");
            if to == "byte" || to == "short" {
                return Ok(format!("({to}){v}"));
            }
            return Ok(v);
        }
        if let (Some(a), Some(b)) = (numeric_rank(&from), numeric_rank(&to))
            && a <= b
        {
            return Ok(base);
        }
        Ok(format!("({to})({base})"))
    }

    /// `expr` coerced to an argument of type `want`.
    fn coerce_arg(&mut self, expr: &Expr, want: &Ty, want_opt: bool) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (got_ty, got_opt) = prog.expr_ty(self.body, expr);
        if got_opt != want_opt {
            return Ok(text);
        }
        if got_opt && want_opt {
            return Ok(text);
        }
        self.prim_coerce(text, &got_ty, want)
    }

    /// `expr` as an `int` (casts a `long` down).
    fn as_int(&mut self, expr: &Expr) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (ty, opt) = prog.expr_ty(self.body, expr);
        let base = if opt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &ty, &Ty::Int(IntTy::I32))
    }

    /// `expr` as a `long`.
    fn as_long(&mut self, expr: &Expr) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (ty, opt) = prog.expr_ty(self.body, expr);
        let base = if opt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &ty, &Ty::Int(IntTy::I64))
    }

    /// `expr` as a `float` / `double`.
    fn as_float(&mut self, expr: &Expr) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (ty, opt) = prog.expr_ty(self.body, expr);
        let base = if opt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &ty, &Ty::F32)
    }

    fn as_double(&mut self, expr: &Expr) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (ty, opt) = prog.expr_ty(self.body, expr);
        let base = if opt { format!("{text}.get()") } else { text };
        self.prim_coerce(base, &ty, &Ty::F64)
    }

    fn as_bytes(&mut self, expr: &Expr) -> BpsResult<String> {
        let text = self.expr(expr)?;
        let prog = self.data.prog;
        let (_, opt) = prog.expr_ty(self.body, expr);
        Ok(if opt { format!("{text}.get()") } else { text })
    }

    /// A repeat count that is a plain integer local or field (possibly
    /// widened to `i64` by the program): the loop uses it as is, with a
    /// negative check unless it is unsigned.
    fn plain_count(&mut self, n: &Expr) -> BpsResult<Option<(String, bool)>> {
        let inner = match n {
            Expr::Cast {
                expr,
                to: Ty::Int(IntTy::I64),
            } => expr.as_ref(),
            other => other,
        };
        if !matches!(inner, Expr::Local(_) | Expr::Field { .. }) {
            return Ok(None);
        }
        let prog = self.data.prog;
        let (ty, optional) = prog.expr_ty(self.body, inner);
        let Ty::Int(int) = ty else {
            return Ok(None);
        };
        if optional || int == IntTy::I128 {
            return Ok(None);
        }
        Ok(Some((self.expr(inner)?, !int.signed())))
    }

    /// The decode call of codec `c`, qualified when it lives in another
    /// wrapper class.
    fn decode_call(&mut self, c: CodecIdx, args: &[Expr]) -> BpsResult<String> {
        let prog = self.data.prog;
        let codec = &prog.codecs[c];
        let cur = self.cursor.clone();
        let mut call = match place_of(prog, c) {
            Place::Owned(t) => {
                let target = self.data.type_ref(self.data.resolve(t), &self.owner);
                format!("{target}.decode({cur}")
            }
            Place::Free => {
                let owner = self.data.owner_of(&codec.origin);
                let prefix = if owner == self.owner {
                    String::new()
                } else {
                    format!("{owner}.")
                };
                let fname = pascal(&codec.name);
                format!("{prefix}decode{fname}({cur}")
            }
        };
        for (arg, param) in args.iter().zip(codec.params.iter()) {
            call.push_str(", ");
            call.push_str(&self.coerce_arg(arg, &param.ty, param.optional)?);
        }
        call.push(')');
        Ok(call)
    }

    /// The encode call of codec `c`: an instance call for records, a static
    /// dispatch for sums, enums, and free codecs.
    fn encode_call(&mut self, c: CodecIdx, args: &[Expr], value: &Expr) -> BpsResult<String> {
        let prog = self.data.prog;
        let codec = &prog.codecs[c];
        let cur = self.cursor.clone();
        let arg_list = {
            let mut list = String::new();
            for (arg, param) in args.iter().zip(codec.params.iter()) {
                list.push_str(", ");
                list.push_str(&self.coerce_arg(arg, &param.ty, param.optional)?);
            }
            list
        };
        match place_of(prog, c) {
            Place::Owned(t) => {
                let r = self.data.resolve(t);
                if matches!(prog.types[r].kind, TypeKind::Record { .. }) {
                    let vtext = self.expr(value)?;
                    Ok(format!("{vtext}.encode({cur}{arg_list})"))
                } else {
                    let target = self.data.type_ref(r, &self.owner);
                    let vtext = self.expr(value)?;
                    let (got, gopt) = prog.expr_ty(self.body, value);
                    let v = self.coerce_ty(vtext, &got, gopt, &codec.value, false)?;
                    Ok(format!("{target}.encode({cur}, {v}{arg_list})"))
                }
            }
            Place::Free => {
                let owner = self.data.owner_of(&codec.origin);
                let prefix = if owner == self.owner {
                    String::new()
                } else {
                    format!("{owner}.")
                };
                let fname = pascal(&codec.name);
                let vtext = self.expr(value)?;
                let (got, gopt) = prog.expr_ty(self.body, value);
                let v = self.coerce_ty(vtext, &got, gopt, &codec.value, false)?;
                Ok(format!("{prefix}encode{fname}({cur}, {v}{arg_list})"))
            }
        }
    }
}

/// Locals bound by `for` loops anywhere in `stmts`.
fn collect_foreach(stmts: &[Stmt], out: &mut BTreeSet<usize>) {
    for stmt in stmts {
        match stmt {
            Stmt::ForEach { item, body, .. } => {
                out.insert(*item);
                collect_foreach(body, out);
            }
            Stmt::If { then, els, .. } => {
                collect_foreach(then, out);
                collect_foreach(els, out);
            }
            Stmt::Match { arms, other, .. } => {
                for arm in arms {
                    collect_foreach(&arm.body, out);
                }
                if let Some(other) = other {
                    collect_foreach(other, out);
                }
            }
            Stmt::Repeat { body, .. } => collect_foreach(body, out),
            _ => {}
        }
    }
}

impl BodyGen<'_> {
    fn stmt(&mut self, stmt: &Stmt) -> BpsResult<()> {
        match stmt {
            Stmt::Declare { .. } => Ok(()),
            Stmt::Let { dst, value } => {
                if self.body.locals[dst.local].uses == 0 {
                    return Ok(());
                }
                let text = self.expr(value)?;
                let name = self.local_java[dst.local].clone();
                let prog = self.data.prog;
                let (vty, vopt) = prog.expr_ty(self.body, value);
                if dst.some && !vopt {
                    self.line(&format!("{name} = Optional.of({text});"));
                } else {
                    let stored = self.store(text, &vty, vopt, dst.local)?;
                    self.line(&format!("{name} = {stored};"));
                }
                Ok(())
            }
            Stmt::Read { dst, op } => {
                if !self.is_decode {
                    return Err(emit("emit java: Read in encode".to_string()));
                }
                let cur = self.cursor.clone();
                let call = match op {
                    ReadOp::U8 => format!("{cur}.readU8()"),
                    ReadOp::F32 => format!("{cur}.readF32()"),
                    ReadOp::F64 => format!("{cur}.readF64()"),
                    ReadOp::Bytes(n) => format!("{cur}.readBytes({})", self.as_int(n)?),
                    ReadOp::Rest => format!("{cur}.readRest()"),
                };
                let uses = self.body.locals[dst.local].uses;
                if uses == 0 {
                    self.line(&format!("{call};"));
                    return Ok(());
                }
                let cty = match op {
                    ReadOp::U8 => Ty::Int(IntTy::U8),
                    ReadOp::F32 => Ty::F32,
                    ReadOp::F64 => Ty::F64,
                    ReadOp::Bytes(_) | ReadOp::Rest => Ty::Bytes,
                };
                let name = self.local_java[dst.local].clone();
                let stored = self.store(call, &cty, false, dst.local)?;
                self.line(&format!("{name} = {stored};"));
                Ok(())
            }
            Stmt::Decode { dst, codec, args } => {
                if !self.is_decode {
                    return Err(emit("emit java: Decode in encode".to_string()));
                }
                let prog = self.data.prog;
                let value = &prog.codecs[*codec].value;
                let call = self.decode_call(*codec, args)?;
                if self.body.locals[dst.local].uses == 0 {
                    self.line(&format!("{call};"));
                    return Ok(());
                }
                let name = self.local_java[dst.local].clone();
                let stored = self.store(call, value, false, dst.local)?;
                self.line(&format!("{name} = {stored};"));
                Ok(())
            }
            Stmt::Utf8 { dst, src } => {
                if !self.is_decode {
                    return Err(emit("emit java: Utf8 in encode".to_string()));
                }
                let bytes = self.as_bytes(src)?;
                let call = format!("BpsUtil.decodeUtf8({bytes})");
                if self.body.locals[dst.local].uses == 0 {
                    self.line(&format!("{call};"));
                    return Ok(());
                }
                let name = self.local_java[dst.local].clone();
                let stored = self.store(call, &Ty::Str, false, dst.local)?;
                self.line(&format!("{name} = {stored};"));
                Ok(())
            }
            Stmt::Write { op, value } => {
                if self.is_decode {
                    return Err(emit("emit java: Write in decode".to_string()));
                }
                let cur = self.cursor.clone();
                match op {
                    WriteOp::U8 => {
                        let text = match byte_literal(value, true) {
                            Some(byte) => byte,
                            None => self.as_int(value)?,
                        };
                        self.line(&format!("{cur}.writeU8({text});"));
                    }
                    WriteOp::F32 => {
                        let text = self.as_float(value)?;
                        self.line(&format!("{cur}.writeF32({text});"));
                    }
                    WriteOp::F64 => {
                        let text = self.as_double(value)?;
                        self.line(&format!("{cur}.writeF64({text});"));
                    }
                    WriteOp::Bytes(n) => {
                        let bytes = self.as_bytes(value)?;
                        let count = self.as_int(n)?;
                        self.line(&format!("{cur}.writeFixed({bytes}, {count});"));
                    }
                    WriteOp::Rest => {
                        let bytes = self.as_bytes(value)?;
                        self.line(&format!("{cur}.writeBytes({bytes});"));
                    }
                }
                Ok(())
            }
            Stmt::Encode { codec, args, value } => {
                if self.is_decode {
                    return Err(emit("emit java: Encode in decode".to_string()));
                }
                let call = self.encode_call(*codec, args, value)?;
                self.line(&format!("{call};"));
                Ok(())
            }
            Stmt::Require { cond, text } => {
                let prog = self.data.prog;
                let neg = prog.negated(self.body, cond);
                let check = self.expr(&neg)?;
                self.line(&format!("if ({check}) {{"));
                self.indent += 1;
                self.line(&self.fail(&format!("require failed: {text}")));
                self.indent -= 1;
                self.line("}");
                Ok(())
            }
            Stmt::Unwrap { dst, src, field } => {
                let uses = self.body.locals[dst.local].uses;
                let source = self.expr(src)?;
                let prog = self.data.prog;
                let (sty, sopt) = prog.expr_ty(self.body, src);
                if !sopt {
                    if uses > 0 {
                        let name = self.local_java[dst.local].clone();
                        let stored = self.store(source, &sty, false, dst.local)?;
                        self.line(&format!("{name} = {stored};"));
                    }
                    return Ok(());
                }
                self.line(&format!("if (!{source}.isPresent()) {{"));
                self.indent += 1;
                self.line(&self.fail(&format!("missing {field}")));
                self.indent -= 1;
                self.line("}");
                if uses > 0 {
                    let name = self.local_java[dst.local].clone();
                    let stored = self.prim_coerce(
                        format!("{source}.get()"),
                        &sty,
                        &self.body.locals[dst.local].ty.clone(),
                    )?;
                    self.line(&format!("{name} = {stored};"));
                }
                Ok(())
            }
            Stmt::If { cond, then, els } => {
                let check = self.expr(cond)?;
                self.line(&format!("if ({check}) {{"));
                self.block(then)?;
                if !els.is_empty() {
                    self.line("} else {");
                    self.block(els)?;
                }
                self.line("}");
                Ok(())
            }
            Stmt::Match {
                scrutinee,
                arms,
                other,
            } => {
                let prog = self.data.prog;
                let (sty, sopt) = prog.expr_ty(self.body, scrutinee);
                let subject = self.expr(scrutinee)?;
                let base = if sopt {
                    format!("{subject}.get()")
                } else {
                    subject
                };
                let jt = self.data.base_java(&sty, &self.owner)?;
                let tmp = self.pick("tag");
                self.line(&format!("{jt} {tmp} = {base};"));
                let is_bool = matches!(sty, Ty::Bool);
                for (i, arm) in arms.iter().enumerate() {
                    let mut conds = Vec::new();
                    for tag in &arm.tags {
                        if is_bool {
                            conds.push(format!("{tmp} == {set}", set = (*tag != 0)));
                        } else {
                            conds.push(format!("{tmp} == {lit}", lit = int_lit(*tag)?));
                        }
                    }
                    if conds.is_empty() {
                        conds.push("true".to_string());
                    }
                    if i == 0 {
                        self.line(&format!("if ({conds}) {{", conds = conds.join(" || ")));
                    } else {
                        self.line(&format!(
                            "}} else if ({conds}) {{",
                            conds = conds.join(" || ")
                        ));
                    }
                    self.block(&arm.body)?;
                }
                if let Some(other) = other {
                    self.line("} else {");
                    self.block(other)?;
                } else {
                    self.line("} else {");
                    self.indent += 1;
                    self.line(&format!(
                        "throw new BpsError({message} + {tmp});",
                        message = java_quote(&format!(
                            "{codec}: no match arm for tag ",
                            codec = self.codec_snake
                        ))
                    ));
                    self.indent -= 1;
                }
                self.line("}");
                Ok(())
            }
            Stmt::Repeat {
                mode,
                list,
                item,
                body,
            } => {
                if !self.is_decode {
                    return Err(emit("emit java: Repeat in encode".to_string()));
                }
                let list_name = self.local_java[*list].clone();
                let item_name = self.local_java[*item].clone();
                let list_ty = self.body.locals[*list].ty.clone();
                if !matches!(&list_ty, Ty::List(_)) {
                    return Err(emit("emit java: Repeat list is not a list".to_string()));
                }
                let item_add = if self.body.locals[*item].optional {
                    format!("{item_name}.get()")
                } else {
                    item_name.clone()
                };
                let cur = self.cursor.clone();
                self.line(&format!("{list_name} = new ArrayList<>();"));
                match mode {
                    RepeatMode::Count(n) => {
                        let (total, unsigned) = match self.plain_count(n)? {
                            Some(plain) => plain,
                            None => {
                                let count = self.as_long(n)?;
                                let total = self.pick("n");
                                self.line(&format!("long {total} = {count};"));
                                (total, false)
                            }
                        };
                        if !unsigned {
                            self.open(&format!("if ({total} < 0)"));
                            self.line(&self.fail("negative repeat count"));
                            self.close();
                        }
                        let iv = self.pick("i");
                        self.open(&format!("for (long {iv} = 0; {iv} < {total}; {iv}++)"));
                        self.stmts(body)?;
                        self.line(&format!("{list_name}.add({item_add});"));
                        self.close();
                    }
                    RepeatMode::Until(term) => {
                        let want = match byte_literal(term, true) {
                            Some(byte) => byte,
                            None => {
                                let text = self.as_long(term)?;
                                let want = self.pick("want");
                                self.line(&format!("long {want} = {text};"));
                                want
                            }
                        };
                        self.open(&format!("while ({cur}.remaining() > 0)"));
                        self.open(&format!("if ({cur}.peekU8() == {want})"));
                        self.line(&format!("{cur}.skip(1);"));
                        self.line("break;");
                        self.close();
                        self.stmts(body)?;
                        self.line(&format!("{list_name}.add({item_add});"));
                        self.close();
                    }
                    RepeatMode::UntilEnd => {
                        self.open(&format!("while ({cur}.remaining() > 0)"));
                        self.stmts(body)?;
                        self.line(&format!("{list_name}.add({item_add});"));
                        self.close();
                    }
                }
                Ok(())
            }
            Stmt::ForEach { list, item, body } => {
                if self.is_decode {
                    return Err(emit("emit java: ForEach in decode".to_string()));
                }
                let text = self.expr(list)?;
                let prog = self.data.prog;
                let (_, optional) = prog.expr_ty(self.body, list);
                let range = if optional {
                    format!("{text}.get()")
                } else {
                    text
                };
                let local = &self.body.locals[*item];
                let (ity, iopt) = (local.ty.clone(), local.optional);
                let ejt = self.data.java_ty(&ity, iopt, &self.owner)?;
                let item_name = self.local_java[*item].clone();
                self.open(&format!("for ({ejt} {item_name} : {range})"));
                self.stmts(body)?;
                self.close();
                Ok(())
            }
            Stmt::ExpectVariant {
                dst,
                sum,
                ty,
                variant,
            } => {
                let prog = self.data.prog;
                let text = self.expr(sum)?;
                let (_, optional) = prog.expr_ty(self.body, sum);
                let subject = if optional {
                    format!("{text}.get()")
                } else {
                    text
                };
                let variant_decl = match &prog.types[*ty].kind {
                    TypeKind::Sum { variants } => &variants[*variant],
                    _ => {
                        return Err(emit("emit java: ExpectVariant of a non-sum".to_string()));
                    }
                };
                let variant_name = pascal(&variant_decl.name);
                let sum_name = self.data.type_ref(self.data.resolve(*ty), &self.owner);
                let detail = format!("wrong variant for {sum_name}: expected {variant_name}");
                let bind = dst.filter(|b| self.body.locals[b.local].uses > 0);
                if self.data.direct.contains(&(*ty, *variant)) {
                    let Some(Ty::Named(target)) = &variant_decl.payload else {
                        return Err(emit(
                            "emit java: direct variant without record payload".to_string(),
                        ));
                    };
                    let payload = self.data.type_ref(self.data.resolve(*target), &self.owner);
                    let Some(bind) = bind else {
                        self.open(&format!("if (!({subject} instanceof {payload}))"));
                        self.line(&self.fail(&detail));
                        self.close();
                        return Ok(());
                    };
                    self.open(&format!("if (!({subject} instanceof {payload}))"));
                    self.line(&self.fail(&detail));
                    self.close();
                    let name = self.local_java[bind.local].clone();
                    let value = format!("({payload})({subject})");
                    if bind.some {
                        self.line(&format!("{name} = Optional.of({value});"));
                    } else {
                        let stored = self.store(value, &Ty::Named(*target), false, bind.local)?;
                        self.line(&format!("{name} = {stored};"));
                    }
                    return Ok(());
                }
                let wrap = self.data.wrappers[&(*ty, *variant)].clone();
                let wrap_ref = if self.data.type_owner[*ty] == self.owner {
                    wrap
                } else {
                    format!("{o}.{wrap}", o = self.data.type_owner[*ty])
                };
                let Some(bind) = bind else {
                    self.open(&format!("if (!({subject} instanceof {wrap_ref}))"));
                    self.line(&self.fail(&detail));
                    self.close();
                    return Ok(());
                };
                self.open(&format!("if (!({subject} instanceof {wrap_ref}))"));
                self.line(&self.fail(&detail));
                self.close();
                let accessor = if self.data.ver.supports_records() {
                    "value()".to_string()
                } else {
                    "getValue()".to_string()
                };
                let value = match &variant_decl.payload {
                    None => format!("new {wrap_ref}()"),
                    Some(_) => format!("(({wrap_ref})({subject})).{accessor}"),
                };
                let name = self.local_java[bind.local].clone();
                if bind.some {
                    self.line(&format!("{name} = Optional.of({value});"));
                } else {
                    let pty = match &variant_decl.payload {
                        Some(p) => p.clone(),
                        None => self.body.locals[bind.local].ty.clone(),
                    };
                    let stored = self.store(value, &pty, false, bind.local)?;
                    self.line(&format!("{name} = {stored};"));
                }
                Ok(())
            }
            Stmt::Return(value) => {
                if !self.is_decode {
                    return Err(emit("emit java: Return in encode".to_string()));
                }
                let Some(want) = self.ret_ty.clone() else {
                    return Err(emit("emit java: Return without a value type".to_string()));
                };
                let text = self.expr(value)?;
                let prog = self.data.prog;
                let (vty, vopt) = prog.expr_ty(self.body, value);
                let stored = self.coerce_ty(text, &vty, vopt, &want, false)?;
                self.line(&format!("return {stored};"));
                Ok(())
            }
            Stmt::Fail(failure) => match failure {
                Failure::EncodeUntilEnd => {
                    self.line(&self.fail("encode not supported for repeat mode until_end"));
                    Ok(())
                }
            },
        }
    }
}

