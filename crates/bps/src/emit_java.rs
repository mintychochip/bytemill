/// Package-private helpers shared by the generated codecs.
const BPS_UTIL_JAVA: &str = r#"// Generated by bpsc from a BPS binary-protocol schema. Do not edit.
final class BpsUtil {
    private BpsUtil() {
    }

    static long signExtend(long v, int bits) {
        if (bits <= 0) {
            return 0;
        }
        if (bits >= 64) {
            return v;
        }
        long mask = (1L << bits) - 1;
        long u = v & mask;
        long sign = 1L << (bits - 1);
        return (u ^ sign) - sign;
    }

    static String decodeUtf8(byte[] b) {
        try {
            return java.nio.charset.StandardCharsets.UTF_8.newDecoder()
                .onMalformedInput(java.nio.charset.CodingErrorAction.REPORT)
                .onUnmappableCharacter(java.nio.charset.CodingErrorAction.REPORT)
                .decode(java.nio.ByteBuffer.wrap(b)).toString();
        } catch (java.nio.charset.CharacterCodingException e) {
            throw new BpsError("invalid utf-8");
        }
    }
}
"#;

