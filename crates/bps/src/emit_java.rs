/// Program-wide Java names: one nested name per type, one wrapper per
/// wrapped sum variant, and the set of directly-implemented record payloads.
struct Data<'a> {
    prog: &'a Program,
    ver: JavaVersion,
    type_name: Vec<String>,
    type_owner: Vec<String>,
    type_stem: Vec<String>,
    /// Wrapper nested-class name for each wrapped `(sum, variant)`.
    wrappers: BTreeMap<(TypeIdx, usize), String>,
    /// `(sum, variant)` whose record payload implements the interface itself.
    direct: BTreeSet<(TypeIdx, usize)>,
    /// Record payloads rendered under their sum, never in the type loop.
    direct_targets: BTreeSet<TypeIdx>,
}

impl<'a> Data<'a> {
    fn new(prog: &'a Program, ver: JavaVersion) -> Data<'a> {
        let mut stems: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
        for t in &prog.types {
            stems.entry(prog.output_stem(&t.origin)).or_default();
        }
        for c in &prog.codecs {
            stems.entry(prog.output_stem(&c.origin)).or_default();
        }
        for (stem, taken) in &mut stems {
            let wrapper = stem_class(stem);
            for reserved in [
                wrapper.as_str(),
                "Reader",
                "Writer",
                "BpsError",
                "BpsUtil",
                "Object",
                "String",
                "Class",
                "System",
                "Math",
                "List",
                "ArrayList",
                "Optional",
                "Objects",
                "Arrays",
                "Integer",
                "Long",
                "Byte",
                "Short",
                "Boolean",
                "Float",
                "Double",
                "StandardCharsets",
            ] {
                taken.insert(reserved.to_string());
            }
        }
        let mut type_name = Vec::with_capacity(prog.types.len());
        let mut type_owner = Vec::with_capacity(prog.types.len());
        let mut type_stem = Vec::with_capacity(prog.types.len());
        for t in &prog.types {
            let stem = prog.output_stem(&t.origin);
            let base = pascal(&t.name);
            let taken = stems.entry(stem.clone()).or_default();
            let name = claim_name(taken, &base);
            type_owner.push(stem_class(&stem));
            type_stem.push(stem);
            type_name.push(name);
        }
        // Count record payloads program-wide.
        let mut payload_uses: BTreeMap<TypeIdx, usize> = BTreeMap::new();
        for decl in &prog.types {
            if let TypeKind::Sum { variants } = &decl.kind {
                for v in variants {
                    if let Some(Ty::Named(t)) = &v.payload
                        && matches!(prog.types[*t].kind, TypeKind::Record { .. })
                    {
                        *payload_uses.entry(*t).or_insert(0) += 1;
                    }
                }
            }
        }
        let mut wrappers = BTreeMap::new();
        let mut direct = BTreeSet::new();
        let mut direct_targets = BTreeSet::new();
        for (s, decl) in prog.types.iter().enumerate() {
            if let TypeKind::Sum { variants } = &decl.kind {
                let stem = prog.output_stem(&decl.origin);
                for (v, variant) in variants.iter().enumerate() {
                    let payload = &variant.payload;
                    let is_direct = match payload {
                        Some(Ty::Named(t)) => {
                            matches!(prog.types[*t].kind, TypeKind::Record { .. })
                                && payload_uses.get(t).copied().unwrap_or(0) == 1
                        }
                        _ => false,
                    };
                    if is_direct {
                        direct.insert((s, v));
                        if let Some(Ty::Named(t)) = payload {
                            direct_targets.insert(*t);
                        }
                    } else {
                        let base = format!(
                            "{tname}{vname}",
                            tname = type_name[s],
                            vname = pascal(&variant.name)
                        );
                        let taken = stems.entry(stem.clone()).or_default();
                        wrappers.insert((s, v), claim_name(taken, &base));
                    }
                }
            }
        }
        Data {
            prog,
            ver,
            type_name,
            type_owner,
            type_stem,
            wrappers,
            direct,
            direct_targets,
        }
    }

    /// The wrapper class of the stem `origin` belongs to.
    fn owner_of(&self, origin: &Origin) -> String {
        stem_class(&self.prog.output_stem(origin))
    }

    /// Simple or qualified reference to type `t` from `owner`.
    fn type_ref(&self, t: TypeIdx, owner: &str) -> String {
        if self.type_owner[t] == owner {
            self.type_name[t].clone()
        } else {
            format!(
                "{owner}.{name}",
                owner = self.type_owner[t],
                name = self.type_name[t]
            )
        }
    }

    /// The record or sum type with its `implements` clause resolved: aliases
    /// dissolve, enums answer their base integer.
    fn resolve(&self, mut t: TypeIdx) -> TypeIdx {
        loop {
            if let TypeKind::Alias { target } = &self.prog.types[t].kind {
                t = *target;
            } else {
                return t;
            }
        }
    }
}

struct Printer<'a> {
    data: Data<'a>,
}

impl<'a> Printer<'a> {
    fn new(prog: &'a Program, ver: JavaVersion) -> Printer<'a> {
        Printer {
            data: Data::new(prog, ver),
        }
    }

    /// One wrapper file body per output stem, keyed by class name.
    fn stem_files(&self) -> BpsResult<BTreeMap<String, String>> {
        let mut stems: BTreeMap<String, Vec<TypeIdx>> = BTreeMap::new();
        for (t, stem) in self.data.type_stem.iter().enumerate() {
            stems.entry(stem.clone()).or_default().push(t);
        }
        let mut codecs: BTreeMap<String, Vec<CodecIdx>> = BTreeMap::new();
        for (c, codec) in self.data.prog.codecs.iter().enumerate() {
            if place_of(self.data.prog, c) == Place::Free {
                codecs
                    .entry(self.data.prog.output_stem(&codec.origin))
                    .or_default()
                    .push(c);
            }
        }
        let mut out = BTreeMap::new();
        let mut all: BTreeSet<String> = BTreeSet::new();
        all.extend(stems.keys().cloned());
        all.extend(codecs.keys().cloned());
        for stem in all {
            let class = stem_class(&stem);
            let mut body = String::from(
                "// Generated by bpsc from a BPS binary-protocol schema. Do not edit.\n",
            );
            body.push_str("import java.nio.charset.StandardCharsets;\n");
            body.push_str("import java.util.ArrayList;\n");
            body.push_str("import java.util.Arrays;\n");
            body.push_str("import java.util.List;\n");
            body.push_str("import java.util.Objects;\n");
            body.push_str("import java.util.Optional;\n");
            body.push_str(&format!("\npublic final class {class} {{\n"));
            body.push_str(&format!("    private {class}() {{\n    }}\n"));
            if let Some(types) = stems.get(&stem) {
                for t in types {
                    // Direct sum payloads render under their sum.
                    if self.data.direct_targets.contains(t) {
                        continue;
                    }
                    let decl = self.render_type(*t)?;
                    if !decl.is_empty() {
                        body.push('\n');
                        body.push_str(&decl);
                    }
                }
            }
            if let Some(free) = codecs.get(&stem) {
                for c in free {
                    body.push('\n');
                    body.push_str(&self.render_free_codec(*c)?);
                }
            }
            body.push_str("}\n");
            out.insert(class, body);
        }
        Ok(out)
    }
}

/// Where a codec's methods live: on its type, or as free functions of the
/// wrapper class.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Place {
    Owned(TypeIdx),
    Free,
}

fn place_of(prog: &Program, c: CodecIdx) -> Place {
    if let Some(t) = prog.codecs[c].ty
        && !matches!(prog.types[t].kind, TypeKind::Alias { .. })
        && prog.types[t].codec == Some(c)
    {
        Place::Owned(t)
    } else {
        Place::Free
    }
}

