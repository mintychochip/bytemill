impl Printer<'_> {
    fn type_doc(&self, t: TypeIdx) -> String {
        let decl = &self.data.prog.types[t];
        let name = &self.data.type_name[t];
        match &decl.origin {
            Origin::Packet {
                name: packet,
                routes,
            } => {
                if routes.is_empty() {
                    format!("// {name} is the {packet} packet.")
                } else {
                    let routes = routes
                        .iter()
                        .map(|r| {
                            format!(
                                "{state} {dir} 0x{id:02x}",
                                state = r.state,
                                dir = r.direction,
                                id = r.id
                            )
                        })
                        .collect::<Vec<_>>()
                        .join("; ");
                    format!("// {name} is the {packet} packet ({routes}).")
                }
            }
            Origin::Encoding { name: encoding } => {
                format!("// {name} is the {encoding} encoding.")
            }
            Origin::Enum { name: encoding } => {
                format!("// {name} is the {encoding} enum.")
            }
            Origin::Frame { name: frame } => format!("// {name} is the {frame} frame."),
            Origin::Field { parent, field } => {
                let parent_name = &self.data.type_name[*parent];
                format!("// {name} is the {field} of {parent_name}.")
            }
            Origin::Variant { sum, variant } => {
                let sum_name = &self.data.type_name[*sum];
                let variant_name = match &self.data.prog.types[*sum].kind {
                    TypeKind::Sum { variants } => variants[*variant].name.snake(),
                    _ => "arm".to_string(),
                };
                format!("// {name} is the {variant_name} arm of {sum_name}.")
            }
        }
    }

    fn render_type(&self, t: TypeIdx) -> BpsResult<String> {
        let owner = &self.data.type_owner[t];
        let name = &self.data.type_name[t];
        let doc = self.type_doc(t);
        match &self.data.prog.types[t].kind {
            TypeKind::Alias { .. } => Ok(String::new()),
            TypeKind::Record { .. } => self.render_record(t, owner, name, &doc, None),
            TypeKind::Sum { .. } => self.render_sum(t, owner, name, &doc),
            TypeKind::Enum { .. } => self.render_enum(t, owner, name, &doc),
        }
    }

    /// `(java type, java name)` of every field of record `t`.
    fn record_fields(&self, t: TypeIdx, owner: &str) -> BpsResult<Vec<(String, String)>> {
        let TypeKind::Record { fields } = &self.data.prog.types[t].kind else {
            return Err(emit("emit java: not a record".to_string()));
        };
        fields
            .iter()
            .map(|f| {
                Ok((
                    self.data.java_ty(&f.ty, f.optional, owner)?,
                    field_java(&f.name),
                ))
            })
            .collect()
    }

    /// The decode/encode methods owned by type `t` (its codec), indented one
    /// extra level for a member type.
    fn owned_methods(&self, t: TypeIdx, owner: &str, indent: &str) -> BpsResult<String> {
        let Some(c) = self.data.prog.types[t].codec else {
            return Ok(String::new());
        };
        if place_of(self.data.prog, c) != Place::Owned(t) {
            return Ok(String::new());
        }
        let codec = &self.data.prog.codecs[c];
        let snake = codec.name.snake();
        let mut out = String::new();
        let ret = self.data.java_ty(&codec.value, false, owner)?;
        // Decode.
        {
            let mut bg = BodyGen::new(&self.data, &codec.decode, &snake, true, owner);
            bg.ret_ty = Some(codec.value.clone());
            bg.indent = 3;
            let mut sig = format!("{indent}public static {ret} decode(Reader r");
            for (param, local) in codec.params.iter().zip(codec.decode.params.iter()) {
                let ty = self.data.java_ty(&param.ty, param.optional, owner)?;
                sig.push_str(&format!(", {ty} {lname}", lname = bg.local_java[*local]));
            }
            sig.push_str(") {\n");
            out.push_str(&sig);
            out.push_str(&bg.body_text()?);
            out.push_str(&format!("{indent}}}\n"));
        }
        // Encode.
        {
            let mut bg = BodyGen::new(&self.data, &codec.encode, &snake, false, owner);
            bg.indent = 3;
            let Some(value_id) = codec.encode.value else {
                return Err(emit(format!("emit java: {snake} has no encode value")));
            };
            let is_record = matches!(
                self.data.prog.types[self.data.resolve(t)].kind,
                TypeKind::Record { .. }
            );
            if is_record {
                bg.value_this = Some(value_id);
            }
            let kind = &self.data.prog.types[self.data.resolve(t)].kind;
            let vname = bg.local_java[value_id].clone();
            let mut sig = if matches!(kind, TypeKind::Record { .. }) {
                format!("{indent}public void encode(Writer w")
            } else if matches!(kind, TypeKind::Sum { .. }) {
                let me = self.data.type_ref(t, owner);
                format!("{indent}public static void encode(Writer w, {me} {vname}")
            } else {
                format!("{indent}public static void encode(Writer w, {ret} {vname}")
            };
            for (param, local) in codec.params.iter().zip(codec.encode.params.iter()) {
                let ty = self.data.java_ty(&param.ty, param.optional, owner)?;
                sig.push_str(&format!(", {ty} {lname}", lname = bg.local_java[*local]));
            }
            sig.push_str(") {\n");
            out.push_str(&sig);
            out.push_str(&bg.body_text()?);
            out.push_str(&format!("{indent}}}\n"));
        }
        Ok(out)
    }

    fn render_record(
        &self,
        t: TypeIdx,
        owner: &str,
        name: &str,
        doc: &str,
        implements: Option<&str>,
    ) -> BpsResult<String> {
        let fields = self.record_fields(t, owner)?;
        let impl_clause = implements.map_or_else(String::new, |s| format!(" implements {s}"));
        if self.data.ver.supports_records() {
            let params = fields
                .iter()
                .map(|(ty, n)| format!("{ty} {n}"))
                .collect::<Vec<_>>()
                .join(", ");
            let mut out =
                format!("    {doc}\n    public record {name}({params}){impl_clause} {{\n");
            let methods = self.owned_methods(t, owner, "        ")?;
            out.push_str(&methods);
            out.push_str("    }\n");
            Ok(out)
        } else {
            let mut out =
                format!("    {doc}\n    public static final class {name}{impl_clause} {{\n");
            for (ty, n) in &fields {
                out.push_str(&format!("        private final {ty} {n};\n"));
            }
            out.push('\n');
            let params = fields
                .iter()
                .map(|(ty, n)| format!("{ty} {n}"))
                .collect::<Vec<_>>()
                .join(", ");
            out.push_str(&format!("        public {name}({params}) {{\n"));
            for (_, n) in &fields {
                out.push_str(&format!("            this.{n} = {n};\n"));
            }
            out.push_str("        }\n\n");
            for (ty, n) in &fields {
                out.push_str(&format!(
                    "        public {ty} {}() {{\n            return {n};\n        }}\n\n",
                    getter(n)
                ));
            }
            // equals / hashCode / toString.
            out.push_str("        @Override\n");
            out.push_str("        public boolean equals(Object o) {\n");
            out.push_str("            if (this == o) {\n");
            out.push_str("                return true;\n");
            out.push_str("            }\n");
            out.push_str(&format!("            if (!(o instanceof {name})) {{\n"));
            out.push_str("                return false;\n");
            out.push_str("            }\n");
            out.push_str(&format!("            {name} other = ({name}) o;\n"));
            let mut tests = Vec::new();
            for (i, f) in self.data.prog.fields(t).iter().enumerate() {
                let n = &fields[i].1;
                tests.push(if f.optional {
                    format!("Objects.equals({n}, other.{n})")
                } else {
                    match &f.ty {
                        Ty::Int(_) | Ty::Bool | Ty::F32 | Ty::F64 => {
                            format!("{n} == other.{n}")
                        }
                        Ty::Bytes => format!("Arrays.equals({n}, other.{n})"),
                        _ => format!("Objects.equals({n}, other.{n})"),
                    }
                });
            }
            if tests.is_empty() {
                out.push_str("            return true;\n");
            } else {
                out.push_str(&format!("            return {};\n", tests.join(" && ")));
            }
            out.push_str("        }\n\n");
            out.push_str("        @Override\n");
            out.push_str("        public int hashCode() {\n");
            let mut hashes = Vec::new();
            for (i, f) in self.data.prog.fields(t).iter().enumerate() {
                let n = &fields[i].1;
                hashes.push(if f.optional {
                    n.clone()
                } else {
                    match &f.ty {
                        Ty::Bytes => format!("Arrays.hashCode({n})"),
                        _ => n.clone(),
                    }
                });
            }
            if hashes.is_empty() {
                out.push_str("            return 0;\n");
            } else {
                out.push_str(&format!(
                    "            return Objects.hash({});\n",
                    hashes.join(", ")
                ));
            }
            out.push_str("        }\n\n");
            out.push_str("        @Override\n");
            out.push_str("        public String toString() {\n");
            if fields.is_empty() {
                out.push_str(&format!("            return \"{name}{{}}\";\n"));
            } else {
                out.push_str(&format!("            return \"{name}{{"));
                for (i, (_, n)) in fields.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(&format!("{n}=\" + {n} + \""));
                }
                out.push_str("}\";\n");
            }
            out.push_str("        }\n\n");
            let methods = self.owned_methods(t, owner, "        ")?;
            out.push_str(&methods);
            out.push_str("    }\n");
            Ok(out)
        }
    }

    fn render_sum(&self, t: TypeIdx, owner: &str, name: &str, doc: &str) -> BpsResult<String> {
        let TypeKind::Sum { variants } = &self.data.prog.types[t].kind else {
            return Err(emit("emit java: not a sum".to_string()));
        };
        let mut out = String::new();
        if self.data.ver.supports_sealed_classes() {
            let mut permits = Vec::new();
            for (v, variant) in variants.iter().enumerate() {
                if self.data.direct.contains(&(t, v)) {
                    let Some(Ty::Named(target)) = &variant.payload else {
                        return Err(emit(format!(
                            "emit java: {name}::{} is not a direct record",
                            variant.name.snake()
                        )));
                    };
                    permits.push(self.data.type_ref(self.data.resolve(*target), owner));
                } else {
                    permits.push(self.data.wrappers[&(t, v)].clone());
                }
            }
            out.push_str(&format!("    {doc}\n"));
            out.push_str(&format!(
                "    public sealed interface {name} permits {} {{\n",
                permits.join(", ")
            ));
            out.push_str(&self.owned_methods(t, owner, "        ")?);
            out.push_str("    }\n");
        } else {
            out.push_str(&format!("    {doc}\n    public interface {name} {{\n"));
            out.push_str(&self.owned_methods(t, owner, "        ")?);
            out.push_str("    }\n");
        }
        for (v, variant) in variants.iter().enumerate() {
            if self.data.direct.contains(&(t, v)) {
                let Some(Ty::Named(target)) = &variant.payload else {
                    return Err(emit(format!(
                        "emit java: {name}::{} is not a direct record",
                        variant.name.snake()
                    )));
                };
                let target = self.data.resolve(*target);
                let tdoc = self.type_doc(target);
                let tname = &self.data.type_name[target];
                out.push('\n');
                out.push_str(&self.render_record(target, owner, tname, &tdoc, Some(name))?);
                continue;
            }
            let wrap = self.data.wrappers[&(t, v)].clone();
            let wdoc = format!(
                "// {wrap} is the {} variant of {name}.",
                variant.name.snake()
            );
            out.push('\n');
            match &variant.payload {
                None => {
                    if self.data.ver.supports_records() {
                        out.push_str(&format!(
                            "    {wdoc}\n    public record {wrap}() implements {name} {{\n    }}\n"
                        ));
                    } else {
                        out.push_str(&format!("    {wdoc}\n"));
                        out.push_str(&format!(
                            "    public static final class {wrap} implements {name} {{\n"
                        ));
                        out.push_str("        @Override\n");
                        out.push_str("        public boolean equals(Object o) {\n");
                        out.push_str(&format!("            return o instanceof {wrap};\n"));
                        out.push_str("        }\n\n");
                        out.push_str("        @Override\n");
                        out.push_str("        public int hashCode() {\n");
                        out.push_str("            return 0;\n");
                        out.push_str("        }\n\n");
                        out.push_str("        @Override\n");
                        out.push_str("        public String toString() {\n");
                        out.push_str(&format!("            return \"{wrap}{{}}\";\n"));
                        out.push_str("        }\n");
                        out.push_str("    }\n");
                    }
                }
                Some(payload) => {
                    let pty = self.data.java_ty(payload, false, owner)?;
                    if self.data.ver.supports_records() {
                        out.push_str(&format!(
                            "    {wdoc}\n    public record {wrap}({pty} value) implements {name} {{\n    }}\n"
                        ));
                    } else {
                        out.push_str(&format!("    {wdoc}\n"));
                        out.push_str(&format!(
                            "    public static final class {wrap} implements {name} {{\n"
                        ));
                        out.push_str(&format!("        public final {pty} value;\n\n"));
                        out.push_str(&format!("        public {wrap}({pty} value) {{\n"));
                        out.push_str("            this.value = value;\n");
                        out.push_str("        }\n\n");
                        out.push_str(&format!(
                            "        public {pty} getValue() {{\n            return value;\n        }}\n\n"
                        ));
                        out.push_str("        @Override\n");
                        out.push_str("        public boolean equals(Object o) {\n");
                        out.push_str(&format!("            if (!(o instanceof {wrap})) {{\n"));
                        out.push_str("                return false;\n");
                        out.push_str("            }\n");
                        out.push_str(&format!("            {wrap} other = ({wrap}) o;\n"));
                        match payload {
                            Ty::Int(_) | Ty::Bool | Ty::F32 | Ty::F64 => {
                                out.push_str("            return value == other.value;\n");
                            }
                            Ty::Bytes => {
                                out.push_str(
                                    "            return Arrays.equals(value, other.value);\n",
                                );
                            }
                            _ => {
                                out.push_str(
                                    "            return Objects.equals(value, other.value);\n",
                                );
                            }
                        }
                        out.push_str("        }\n\n");
                        out.push_str("        @Override\n");
                        out.push_str("        public int hashCode() {\n");
                        match payload {
                            Ty::Bytes => {
                                out.push_str("            return Arrays.hashCode(value);\n");
                            }
                            _ => {
                                out.push_str("            return Objects.hash(value);\n");
                            }
                        }
                        out.push_str("        }\n\n");
                        out.push_str("        @Override\n");
                        out.push_str("        public String toString() {\n");
                        out.push_str(&format!(
                            "            return \"{wrap}{{value=\" + value + \"}}\";\n"
                        ));
                        out.push_str("        }\n");
                        out.push_str("    }\n");
                    }
                }
            }
        }
        Ok(out)
    }

    fn render_enum(&self, t: TypeIdx, owner: &str, name: &str, doc: &str) -> BpsResult<String> {
        let TypeKind::Enum { base, members } = &self.data.prog.types[t].kind else {
            return Err(emit("emit java: not an enum".to_string()));
        };
        let base_java = int_java(*base)?;
        let mut out = format!("    {doc}\n    public static final class {name} {{\n");
        out.push_str(&format!("        private {name}() {{\n        }}\n\n"));
        for m in members {
            out.push_str(&format!(
                "        public static final {base_java} {} = {};\n",
                m.name.screaming(),
                int_lit(m.value)?,
            ));
        }
        out.push('\n');
        out.push_str(&self.owned_methods(t, owner, "        ")?);
        out.push_str("    }\n");
        Ok(out)
    }

    /// Free codec functions (scalar, string, and nested codecs) as public
    /// static methods of the wrapper class.
    fn render_free_codec(&self, c: CodecIdx) -> BpsResult<String> {
        let codec = &self.data.prog.codecs[c];
        let owner = self.data.owner_of(&codec.origin);
        let snake = codec.name.snake();
        let fname = pascal(&codec.name);
        let mut out = String::new();
        {
            let mut bg = BodyGen::new(&self.data, &codec.decode, &snake, true, &owner);
            bg.ret_ty = Some(codec.value.clone());
            let ret = self.data.java_ty(&codec.value, false, &owner)?;
            let mut sig = format!("    public static {ret} decode{fname}(Reader r");
            for (param, local) in codec.params.iter().zip(codec.decode.params.iter()) {
                let ty = self.data.java_ty(&param.ty, param.optional, &owner)?;
                sig.push_str(&format!(", {ty} {lname}", lname = bg.local_java[*local]));
            }
            sig.push_str(") {\n");
            out.push_str(&sig);
            out.push_str(&bg.body_text()?);
            out.push_str("    }\n");
        }
        {
            let mut bg = BodyGen::new(&self.data, &codec.encode, &snake, false, &owner);
            let Some(value_id) = codec.encode.value else {
                return Err(emit(format!("emit java: {snake} has no encode value")));
            };
            let vty = self.data.java_ty(&codec.value, false, &owner)?;
            let vname = bg.local_java[value_id].clone();
            let mut sig = format!("    public static void encode{fname}(Writer w, {vty} {vname}");
            for (param, local) in codec.params.iter().zip(codec.encode.params.iter()) {
                let ty = self.data.java_ty(&param.ty, param.optional, &owner)?;
                sig.push_str(&format!(", {ty} {lname}", lname = bg.local_java[*local]));
            }
            sig.push_str(") {\n");
            out.push_str(&sig);
            out.push_str(&bg.body_text()?);
            out.push_str("    }\n");
        }
        Ok(out)
    }
}

/// An integer literal: plain when it fits an `int`, `L`-suffixed otherwise.
/// Values arrive as `i64` (expressions) or `i128` (match tags, enum members).
fn int_lit(value: i128) -> BpsResult<String> {
    if value >= i128::from(i32::MIN) && value <= i128::from(i32::MAX) {
        Ok(value.to_string())
    } else if value >= i128::from(i64::MIN) && value <= i128::from(i64::MAX) {
        Ok(format!("{value}L"))
    } else {
        Err(emit(format!(
            "emit java: integer {value} has no Java literal"
        )))
    }
}

/// The spelling of a mask operand: hexadecimal above 9 like the other
/// printers (`0xFF`), decimal otherwise.
fn mask_operand(value: i64) -> String {
    if value > 9 {
        if value >= i64::from(i32::MIN) && value <= i64::from(i32::MAX) {
            format!("0x{value:X}")
        } else {
            format!("0x{value:X}L")
        }
    } else {
        value.to_string()
    }
}

