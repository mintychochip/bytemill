//! `emit java`: an idiomatic Java package over the typed program.
//!
//! The printer reads [`Program`](crate::ir::typed) only: every name is already
//! resolved, every value typed, every nested record or sum lifted into its own
//! codec. It chooses Java syntax and nothing else.
//!
//! # Files
//!
//! `bpsgen/` holds `Reader.java` (a cursor over `byte[]`), `Writer.java` (a
//! growing byte buffer), `BpsError.java` (the unchecked failure type),
//! `BpsUtil.java` (package-private helpers), and one `{Stem}.java` per route
//! category (types and codecs, in program order). A packet routed only as
//! `play_clientbound` lands in `PlayClientbound.java`; a packet routed in
//! several state/direction pairs is `Shared.java`; encodings, enums, frames,
//! and unrouted packets are `Encoding.java` and `Unrouted.java`. The stem file
//! names are PascalCase because Java requires the public top-level class to
//! match its file. Everything is in the default package so the tree compiles
//! with `javac` and runs with single-file source launch alike.
//!
//! # Names
//!
//! PascalCase for types, SCREAMING_SNAKE_CASE for enum constants, camelCase
//! for fields, methods, locals, and parameters. A name that would collide
//! with a Java keyword, an `Object` method (record components), or a
//! runtime/nesting scope takes a trailing `_`; a nested type that would
//! shadow a sibling scope is numbered.
//!
//! # Types
//!
//! Records are `record`s on Java 17+ and `final` classes with constructors,
//! getters, `equals`, `hashCode`, and `toString` before that. Sums are
//! `sealed` interfaces with one record per variant on Java 17+ (a block-arm
//! record implements the interface itself when it is only that variant's
//! payload, otherwise the variant wraps it) and plain interfaces with
//! `final` variant classes before that. Enums are open: a `final` class of
//! integer constants whose codec reads and writes the base integer, so a
//! decoded value that is not a member survives. Optionals are `Optional`,
//! lists are `List`, bytes are `byte[]`.
//!
//! # Codecs
//!
//! `static Probe decode(Reader r, ...)` and `void encode(Writer w, ...)` live
//! on each record, sum, enum, or free codec; failures throw `BpsError`
//! carrying the codec and a detail message (reads also know the offset).
//! Integer operators are plain Java operators (fixed-width Java arithmetic
//! wraps, never traps); signed division and modulo use `Math.floorDiv` and
//! `Math.floorMod` when the dividend may be negative; unsigned values live in
//! the next-wider signed Java type so comparisons need no masking. Locals are
//! declared up front with their zero value; counted loops are
//! `for (long i = 0; i < n; i++)`; list loops are enhanced `for` loops.

