//! In-tree packet rendering from a ledger shape plus a wire body.
//! Ports `bps/tree_packet.py`.

use crate::emit_rstom::PacketBody;
use crate::errors::{emit, py_repr_str, BpsResult};
use crate::minestom::Unit;
use crate::shapes::model::{FieldShape, Shape};

const COPY_TYPES: &[&str] = &[
    "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64", "bool", "Uuid",
];

const MAX_LINES: usize = 400;
const FRAMES_PREFIX: &str = "crate::frames::";

/// `_guard_frames_walkers`: the first `crate::frames::<name>` in reads, then writes.
fn guard_frames_walkers(module: &str, body: &PacketBody) -> BpsResult<()> {
    for chunk in [&body.reads, &body.writes] {
        let mut rest = chunk.as_str();
        while let Some(pos) = rest.find(FRAMES_PREFIX) {
            let after = &rest[pos + FRAMES_PREFIX.len()..];
            let name: String = after
                .chars()
                .take_while(|c| c.is_ascii_lowercase() || *c == '_')
                .collect();
            if !name.is_empty() {
                return Err(emit(format!(
                    "{module}: packet needs the frames walker {name}, which rstom does not provide yet"
                )));
            }
            rest = after;
        }
    }
    Ok(())
}

/// `_validate_shape`.
pub fn validate_shape(shape: &Shape) -> BpsResult<()> {
    if shape.form == "unit" && !shape.fields.is_empty() {
        return Err(emit(format!("{}: unit shape must have no fields", shape.module)));
    }
    if shape.serializer.style == "constant" && shape.form != "unit" {
        return Err(emit(format!(
            "{}: constant serializer requires unit form",
            shape.module
        )));
    }
    if shape.form == "unit" && shape.serializer.read_via_new {
        return Err(emit(format!(
            "{}: unit packet cannot use read_via_new",
            shape.module
        )));
    }
    Ok(())
}

fn is_copy_field(rust_type: &str) -> bool {
    if let Some(inner) = rust_type
        .strip_prefix("Option<")
        .and_then(|s| s.strip_suffix('>'))
    {
        return is_copy_field(inner);
    }
    if rust_type.starts_with("Vec<") {
        return false;
    }
    COPY_TYPES.contains(&rust_type)
}

fn adapt_tree_writes(writes: &str, fields: &[FieldShape]) -> String {
    let mut out = writes.to_string();
    for f in fields {
        if is_copy_field(&f.type_) {
            out = out.replace(
                &format!("value.{}.clone()", f.name),
                &format!("value.{}", f.name),
            );
        }
    }
    out
}

fn field_init_list(fields: &[FieldShape]) -> String {
    fields
        .iter()
        .map(|f| f.name.as_str())
        .collect::<Vec<_>>()
        .join(",\n            ")
}

fn read_box(cls: &str, form: &str, fields: &[FieldShape]) -> String {
    if form == "unit" {
        return format!("        Box::new({cls})");
    }
    if fields.len() == 1 {
        return format!("        Box::new({cls} {{ {} }})", fields[0].name);
    }
    let init = field_init_list(fields);
    format!("        Box::new({cls} {{\n            {init},\n        }})")
}

fn derive_attr(derives: &[String]) -> String {
    if derives.is_empty() {
        return String::new();
    }
    format!("#[derive({})]\n", derives.join(", "))
}

/// `_doc_lines`: each line prefixed and newline-terminated.
fn doc_lines(prefix: &str, lines: &[String]) -> String {
    lines.iter().map(|l| format!("{prefix}{l}\n")).collect()
}

/// Python `format(n, "0{width}x")` for a signed integer.
fn hex_padded(n: i128, width: usize) -> String {
    let digits = format!("{:x}", n.unsigned_abs());
    let sign = if n < 0 { "-" } else { "" };
    let pad = width.saturating_sub(sign.len() + digits.len());
    format!("{sign}{}{digits}", "0".repeat(pad))
}

fn banner(unit: &Unit) -> String {
    let pkt = &unit.pkt.name;
    let routes = unit
        .routes
        .iter()
        .map(|r| format!("{}.{} 0x{}", r.state, r.direction, hex_padded(r.packet_id, 2)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "//! Generated by `bps emit rust` from schemas/minecraft_26_3*.bps: BPS packet `{pkt}`, routed {routes}.\n"
    )
}

/// `_marker_imports`: (import, impls).
fn marker_imports(unit: &Unit) -> (&'static str, String) {
    let name = &unit.cls.name;
    if unit.cls.group == "client" {
        (
            "use crate::network::packet::client::client_packet::{ClientPacket, ClientPacketGroup};\n",
            format!("impl ClientPacket for {name} {{}}\nimpl ClientPacketGroup for {name} {{}}\n"),
        )
    } else {
        (
            "use crate::network::packet::server::server_packet::{ServerPacket, ServerPacketGroup};\n",
            format!("impl ServerPacket for {name} {{}}\nimpl ServerPacketGroup for {name} {{}}\n"),
        )
    }
}

fn use_block(unit: &Unit, shape: &Shape, body: &PacketBody) -> String {
    let mut lines: Vec<String> = vec!["use std::sync::Arc;\n".into(), "\n".into()];
    let (marker_import, _) = marker_imports(unit);
    if shape.serializer.style == "struct" {
        lines.push("use crate::network::buffer::NetworkBuffer;\n".into());
    }
    lines.push(marker_import.into());
    lines.push("use crate::network::packet::packet::Packet;\n".into());
    if shape.serializer.style == "constant" {
        lines.push(
            "use crate::network::packet::serializer::{ConstantSerializer, PacketSerializer};\n"
                .into(),
        );
    } else {
        lines.push(
            "use crate::network::packet::serializer::{PacketSerializer, PacketValue, downcast};\n"
                .into(),
        );
    }
    if body.used_wires.len() == 1 {
        lines.push(format!(
            "use crate::network::types::{};\n",
            body.used_wires[0]
        ));
    } else if !body.used_wires.is_empty() {
        lines.push(format!(
            "use crate::network::types::{{{}}};\n",
            body.used_wires.join(", ")
        ));
    }
    if body.needs_fixed_raw_bytes {
        lines.push("use crate::network::types::fixed_raw_bytes;\n".into());
    }
    if body.rtypes.iter().any(|t| t == "Uuid") {
        lines.push("use crate::network::uuid::Uuid;\n".into());
    }
    if body.rtypes.iter().any(|t| t == "CoordVec") {
        lines.push("use crate::coordinate::Vec as CoordVec;\n".into());
    }
    lines.concat()
}

fn struct_decl(shape: &Shape) -> String {
    let docs = doc_lines("/// ", &shape.struct_docs);
    let derive = derive_attr(&shape.derives);
    if shape.form == "unit" {
        return format!("{docs}{derive}pub struct {};", shape.cls);
    }
    let mut field_lines: Vec<String> = Vec::new();
    for f in &shape.fields {
        field_lines.push(
            doc_lines("    /// ", &f.docs)
                .trim_end_matches('\n')
                .to_string(),
        );
        field_lines.push(format!("    pub {}: {},", f.name, f.type_));
    }
    if let Some(last) = field_lines.last_mut() {
        if last.ends_with(',') {
            last.pop();
        }
    }
    let fields = field_lines.join("\n");
    format!("{docs}{derive}pub struct {} {{\n{fields}\n}}", shape.cls)
}

fn new_fn(shape: &Shape) -> String {
    if !shape.new.present {
        return String::new();
    }
    let mut lines: Vec<String> = Vec::new();
    lines.push(
        doc_lines("    /// ", &shape.new.docs)
            .trim_end_matches('\n')
            .to_string(),
    );
    if shape.new.must_use {
        lines.push("    #[must_use]".into());
    }
    for attr in &shape.new.attrs {
        lines.push(format!("    {attr}"));
    }
    let params = shape
        .fields
        .iter()
        .map(|f| format!("{}: {}", f.name, f.type_))
        .collect::<Vec<_>>()
        .join(", ");
    let const_kw = if shape.new.const_ { "const " } else { "" };
    let body = if shape.form == "unit" {
        "        Self".to_string()
    } else {
        format!("        Self {{ {} }}", field_init_list(&shape.fields))
    };
    lines.push(format!("    pub {const_kw}fn new({params}) -> Self {{"));
    if !shape.new.body.is_empty() {
        lines.extend(shape.new.body.iter().cloned());
    } else {
        lines.push(body);
    }
    lines.push("    }".into());
    lines.join("\n")
}

fn serializer_fn(shape: &Shape) -> String {
    let mut lines: Vec<String> = Vec::new();
    lines.push(
        doc_lines("    /// ", &shape.serializer_fn_docs)
            .trim_end_matches('\n')
            .to_string(),
    );
    if shape.serializer_fn_must_use {
        lines.push("    #[must_use]".into());
    }
    lines.push("    pub fn serializer() -> Arc<dyn PacketSerializer> {".into());
    if shape.serializer.style == "constant" {
        lines.push(format!(
            "        Arc::new(ConstantSerializer::new({}))",
            shape.serializer.name
        ));
    } else {
        lines.push(format!("        Arc::new({})", shape.serializer.name));
    }
    lines.push("    }".into());
    lines.join("\n")
}

fn inherent_impl(shape: &Shape) -> String {
    let parts = [new_fn(shape), serializer_fn(shape)];
    let body = parts
        .iter()
        .filter(|p| !p.is_empty())
        .cloned()
        .collect::<Vec<_>>()
        .join("\n\n");
    if body.is_empty() {
        return String::new();
    }
    format!("impl {} {{\n{body}\n}}\n\n", shape.cls)
}

fn serializer_impl(shape: &Shape, body: &PacketBody) -> String {
    if shape.serializer.style == "constant" {
        return String::new();
    }
    let ser = &shape.serializer.name;
    let vis = if shape.serializer.public { "pub " } else { "" };
    let docs = doc_lines("/// ", &shape.serializer.docs);
    let writes = adapt_tree_writes(&body.writes, &shape.fields);
    let read_tail = if shape.serializer.read_via_new {
        if shape.form == "unit" {
            format!("        Box::new({}::new())", shape.cls)
        } else {
            let args = shape
                .fields
                .iter()
                .map(|f| f.name.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            format!("        Box::new({}::new({args}))", shape.cls)
        }
    } else {
        read_box(&shape.cls, &shape.form, &shape.fields)
    };
    format!(
        "{docs}{vis}struct {ser};\n\n\
         impl PacketSerializer for {ser} {{\n\
         \x20   fn write(&self, buffer: &mut NetworkBuffer, value: &PacketValue) {{\n\
         \x20       let value = downcast::<{cls}>(value);\n\
         {writes}\n\
         \x20   }}\n\n\
         \x20   fn read(&self, buffer: &mut NetworkBuffer) -> PacketValue {{\n\
         {reads}\n\
         {read_tail}\n\
         \x20   }}\n\
         }}\n",
        cls = shape.cls,
        reads = body.reads,
    )
}

fn extras_tail(shape: &Shape) -> String {
    match &shape.extras {
        None => String::new(),
        Some(e) if e.is_empty() => String::new(),
        Some(_) => {
            let stem = shape.module.rsplit('/').next().unwrap_or("");
            format!(
                "\n#[path = \"{stem}.ext.rs\"]\nmod ext;\n\
                 #[allow(unused_imports)]\n\
                 pub use ext::*;\n"
            )
        }
    }
}

/// `tree_packet(unit, shape, body)`: render the in-tree packet source.
pub fn tree_packet(unit: &Unit, shape: &Shape, body: &PacketBody) -> BpsResult<String> {
    validate_shape(shape)?;
    guard_frames_walkers(&shape.module, body)?;
    if shape.cls != unit.cls.name {
        return Err(emit(format!(
            "{}: shape class {} != unit {}",
            shape.module,
            py_repr_str(&shape.cls),
            py_repr_str(&unit.cls.name)
        )));
    }

    let mut parts: Vec<String> = vec![banner(unit), "//!\n".into()];
    if !shape.module_docs.is_empty() {
        parts.push(doc_lines("//! ", &shape.module_docs));
    }
    parts.push("\n".into());
    parts.push(use_block(unit, shape, body));
    parts.push("\n".into());
    parts.push(struct_decl(shape));
    parts.push("\n\n".into());
    parts.push(inherent_impl(shape));
    parts.push(format!("impl Packet for {} {{\n", shape.cls));
    parts.push(format!(
        "    const CLASS_NAME: &'static str = \"{}\";\n",
        unit.cls.java
    ));
    parts.push("}\n\n".into());
    let (_, marker_impls) = marker_imports(unit);
    parts.push(marker_impls);
    parts.push("\n".into());
    parts.push(serializer_impl(shape, body));
    parts.push(extras_tail(shape));
    let mut text = parts.concat();
    let newlines = text.matches('\n').count() + usize::from(!text.ends_with('\n'));
    if newlines > MAX_LINES {
        return Err(emit(format!(
            "{}: generated file exceeds {MAX_LINES} lines",
            shape.module
        )));
    }
    if !text.ends_with('\n') {
        text.push('\n');
    }
    Ok(text)
}
